"""R51: the capped ladder and its cap-lifted control, side by side.

One table, one row per apolune level and budget, carrying both tallies and both
median ratios. The registration commits to printing them together wherever a
wide-level magnitude is quoted, so they are generated together and never
assembled by hand.

The cell that changed hands is marked. It is one of sixteen, and a table that
did not point at it would leave a reader to find it by comparing thirty-two
numbers.

Usage:  python rev51_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

BETAS = ["0.50", "0.62", "0.75", "1.00"]
WORDS = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four"}


def fmt_rho(v) -> str:
    if v is None:
        return "--"
    if v >= 1000.0:
        e = 0
        while v >= 10.0:
            v /= 10.0
            e += 1
        return f"${v:.1f}\\times10^{{{e}}}$"
    if v >= 10.0:
        return f"${v:.0f}$"
    if v >= 1.0:
        return f"${v:.2f}$"
    return f"${v:.3f}$"


def main() -> int:
    v = json.loads((METRICS / "r51_verdict.json").read_text(encoding="utf-8"))
    lines = [r"% generated by rev51_tables.py; do not edit",
             r"\begin{tabular}{@{}l l r r r r@{}}",
             r"\toprule",
             r"& & \multicolumn{2}{c}{under the ceiling}"
             r" & \multicolumn{2}{c}{ceiling removed} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
             r"$\beta$ & Apolune & tally & median $\rho$ & tally"
             r" & median $\rho$ \\",
             r"\midrule"]
    changed = 0
    for i, b in enumerate(BETAS):
        blk = v["by_budget"].get(b)
        if not blk:
            continue
        if i:
            lines.append(r"\addlinespace")
        for lvl, r in blk["levels"].items():
            c, u = r["capped"], r["uncapped"]
            # The cell that changes hands is set in bold rather than daggered.
            # The dagger already means two other things in this document, the
            # post-hoc budget on the regime map and the registered pair in the
            # ladder tables, and a third meaning in one table is a reader's
            # problem rather than a typographic economy.
            flip = bool(r.get("verdict_changed"))
            changed += flip

            # \mathbf on each figure, not \textbf around the pair. The tally
            # is set in math mode, so \textbf reached only the dash between
            # the two numbers: the caption promised a bold cell the reader
            # could not find.
            def tally(a, b, flipped: bool = flip) -> str:
                if flipped:
                    return rf"$\mathbf{{{a}}}$--$\mathbf{{{b}}}$"
                return f"${a}$--${b}$"

            cap = tally(c["radial"], c["fixed"])
            unc = tally(u["radial"], u["fixed"])
            lines.append(
                f"${b}$ & ${float(lvl):.0f}$~km & "
                f"{cap} & {fmt_rho(c['median_rho'])} & "
                f"{unc} & {fmt_rho(u['median_rho'])}"
                r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    out = METRICS / "r51_capped_vs_uncapped_table.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    cells = sum(len(blk["levels"]) for blk in v["by_budget"].values())
    macros = {
        "CLcells": str(cells),
        "CLunchanged": str(cells - changed),
        "CLchanged": WORDS.get(changed, str(changed)),
        "CLbudgets": WORDS.get(len(v["by_budget"]), str(len(v["by_budget"]))),
        "CLoutcome": v["outcome"].split("_")[0],
    }
    body = ["% generated by rev51_tables.py; do not edit"]
    body += [f"\\newcommand{{\\{k}}}{{{x}}}" for k, x in macros.items()]
    (METRICS / "r51_capped_vs_uncapped_macros.tex").write_text(
        "\n".join(body) + "\n", encoding="utf-8")

    print(f"[written] {out.name}")
    print(f"  {cells} cells over {len(v['by_budget'])} budgets, "
          f"{changed} changed hands")
    print(f"[written] r51_capped_vs_uncapped_macros.tex ({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
