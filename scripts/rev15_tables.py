"""Tables for the R15 audit-response items.

Emits, into metrics/:
  r15_deployable_table.tex    budget calibration without the reference arc
  r15_fixed_oracle_table.tex  the three fixed comparators at beta = 1

Usage:  python rev15_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

LABEL = {"kepler": "two-body, no propagation",
         "pilot": "$N=40$ pilot arc"}


def deployable() -> str:
    lines = []
    for des in ("A", "B"):
        p = METRICS / f"r15_deployable_calibration_{des}.json"
        if not p.exists():
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        s = d["summary"]
        traj = json.loads((METRICS / f"r14_trajectory_{des}_beta_1.00.json"
                           ).read_text(encoding="utf-8"))["summary"]
        lines.append(f"    \\multicolumn{{8}}{{@{{}}l}}{{\\emph{{Design {des}}}}}\\\\")
        lines.append(
            f"    reference arc (O25) & {traj['orbits']} & 1.0000 & --- & --- & "
            f"{traj['rho_budget']['median']:.3f} & "
            f"{traj['resolved_atallah_wins']}/{traj['resolved_fixed_wins']} & "
            f"{traj['unresolved']}\\\\")
        for v in ("pilot", "kepler"):
            e = s[v]
            lines.append(
                f"    {LABEL[v]} & {e['orbits']} & "
                f"{e['beta_realized']['median']:.4f} & "
                f"{100 * e['abs_calibration_error']['median']:.2f}\\% & "
                f"{100 * e['abs_calibration_error']['max']:.0f}\\% & "
                f"{e['rho_budget']['median']:.3f} & "
                f"{e['resolved_atallah_wins']}/{e['resolved_fixed_wins']} & "
                f"{e['unresolved']}\\\\")
        if des == "A":
            lines.append("    \\midrule")
    body = "\n".join(lines)
    pa = json.loads((METRICS / "r15_deployable_calibration_A.json"
                     ).read_text())["summary"]["pilot_cost_fraction_of_run"]
    return f"""% auto-generated by rev15_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\setlength{{\\tabcolsep}}{{4pt}}
  \\caption{{Budget calibration without the reference arc. The O25 tolerance is
  found by bisecting on the archived reference trajectory's altitude history,
  which no operational user has in advance. The two lower rows of each block
  replace it with information available beforehand: the two-body altitude history
  implied by the initial state, and the altitude history of an $N=40$
  loose-tolerance pilot arc costing a median
  {100 * pa['median']:.0f}\\% of the real run's gravity work. Realized $\\beta$ and
  the calibration error are measured on the true arc.
  $\\rho_{{\\mathrm{{budget}}}}=E_{{\\mathrm{{fix}}}}/E_{{\\mathrm{{At}}}}$, so values
  below unity favor the constant degree. The verdict is unchanged under every
  calibration: what foreknowledge of the arc buys is budget adherence, not
  accuracy.}}
  \\label{{tab:deployable-calibration}}
  \\begin{{tabular}}{{l r r r r r c r}}
    \\toprule
    Calibration & orbits & median $\\beta$ & median err. & worst err. &
      $\\rho_{{\\mathrm{{budget}}}}$ & res.\\ At./fix & unres.\\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""


def fixed_oracle() -> str:
    p = METRICS / "r15_fixed_oracle.json"
    if not p.exists():
        return ""
    d = json.loads(p.read_text(encoding="utf-8"))
    s = d["summary"]
    lines = []
    for r in d["rows"]:
        lines.append(
            f"    {r['design']} & {r['sobol_index']:03d} & {r['hp_km']:.0f} & "
            f"{r['n_critical']} & {r['n_sat']} & {r['n_oracle']} & "
            f"{r['error_sat_m']:.3f} & {r['error_oracle_m']:.3f} & "
            f"{r['oracle_gain_over_sat']:.2f} & {r['atallah_error_m']:.3f} & "
            f"{r['rho_vs_sat']:.3f} & {r['rho_vs_oracle']:.3f}\\\\")
    body = "\n".join(lines)
    return f"""% auto-generated by rev15_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\setlength{{\\tabcolsep}}{{3.5pt}}
  \\caption{{Three fixed comparators at $\\beta = 1$. $N_{{\\mathrm{{sat}}}}$ is the
  budget-saturating degree, the largest whose per-call quadratic work fits the
  budget; $N_{{\\mathrm{{oracle}}}}$ is the degree that actually minimizes the
  seven-day error over a declared ladder of offsets below it, found post hoc and
  not selectable in advance. The seven-day error is not monotone in degree, so
  these differ. $\\rho$ columns are the fixed error over the radial rule's, so
  values below unity favor the constant degree. The oracle can only improve the
  fixed side, so it can only strengthen a conclusion that already favors it: the
  constant degree is the more accurate policy on
  {s['fixed_beats_radial_vs_sat']} of {s['orbits']} orbits against
  $N_{{\\mathrm{{sat}}}}$ and {s['fixed_beats_radial_vs_oracle']} of {s['orbits']}
  against $N_{{\\mathrm{{oracle}}}}$.}}
  \\label{{tab:fixed-oracle}}
  \\begin{{tabular}}{{l r r r r r r r r r r r}}
    \\toprule
    Des. & idx & $h_p$ & $N_{{\\mathrm{{crit}}}}$ & $N_{{\\mathrm{{sat}}}}$ &
      $N_{{\\mathrm{{oracle}}}}$ & $E_{{\\mathrm{{sat}}}}$ &
      $E_{{\\mathrm{{oracle}}}}$ & gain & $E_{{\\mathrm{{At}}}}$ &
      $\\rho_{{\\mathrm{{sat}}}}$ & $\\rho_{{\\mathrm{{oracle}}}}$\\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""


def main() -> int:
    (METRICS / "r15_deployable_table.tex").write_text(deployable(),
                                                      encoding="utf-8")
    print("[written] r15_deployable_table.tex")
    fo = fixed_oracle()
    if fo:
        (METRICS / "r15_fixed_oracle_table.tex").write_text(fo, encoding="utf-8")
        print("[written] r15_fixed_oracle_table.tex")
    else:
        print("[skip] r15_fixed_oracle.json not present yet")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
