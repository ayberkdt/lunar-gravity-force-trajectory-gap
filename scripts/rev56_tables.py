"""The wide-elliptic population under expanded dynamics, as a table.

Three budgets, one population, one dynamics model. The table is generated from
the three sealed score records rather than typed, so the printed numbers cannot
drift from the records the campaign wrote.

The two median ratios are the point of the table. revJ2 reports rho as
radial-over-constant, which is the reciprocal of the main text's
rho_budget = E_fix / E_rad, so a value below one means the radial endpoint is
ahead. Printing both the gravity-only and the full-dynamics median in adjacent
columns is what makes the shift in the crossing readable: the two disagree at
0.75 and agree at the budgets either side of it.

Usage:  python rev56_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

DESIGN = "OEU"
BUDGETS = ("0.62", "0.75", "1.00")
# Named rJ_ rather than r56_ so that revJ_finalize_manifest, which globs
# rJ_*.tex, owns it. The campaign ran under the J2 plan machinery and its score
# records already sit in the rJ manifest; the table it prints belongs in the
# same partition rather than orphaned beside it.
OUT = METRICS / "rJ_geometry_dynamics_table.tex"


def score(beta: str) -> dict:
    suffix = "" if beta == "1.00" else f"_beta_{beta}"
    p = METRICS / f"rJ2_score{suffix}_design{DESIGN}.json"
    return json.loads(p.read_text(encoding="utf-8"))


def main() -> int:
    rows = []
    for beta in BUDGETS:
        d = score(beta)
        c, a = d["counts"], d["aggregates"]
        rows.append({
            "beta": beta,
            "orbits": c["orbits"],
            "resolved": c["resolved_tighter"],
            "both": c["resolved_in_both_dynamics"],
            "agree": c["sign_agrees_resolved_in_both"],
            "rho_full": a["median_rho_traj"],
            "rho_grav": a["median_rho_traj_gravity_only"],
            "beta_real": a["median_realized_beta_radial"],
            "verdict": d["verdict"],
        })

    lines = [
        "% auto-generated by rev56_tables.py -- do not edit by hand",
        r"\begin{tabular}{l r r r r r r}",
        r"  \toprule",
        r"  & orbits & resolved & resolved & sign & "
        r"$\tilde\rho$ full & $\tilde\rho$ grav.\\",
        r"  $\beta$ & & (full) & in both & agrees & dynamics & only\\",
        r"  \midrule",
    ]
    for r in rows:
        lines.append(
            f"  ${r['beta']}$ & {r['orbits']} & {r['resolved']} & {r['both']} "
            f"& {r['agree']} & {r['rho_full']:.2f} & {r['rho_grav']:.2f}\\\\")
    lines += [r"  \bottomrule", r"\end{tabular}"]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[written] {OUT.name}")
    for r in rows:
        side_full = "radial" if r["rho_full"] < 1 else "constant"
        side_grav = "radial" if r["rho_grav"] < 1 else "constant"
        print(f"  beta={r['beta']}  {r['agree']}/{r['both']} agree  "
              f"rho full {r['rho_full']:.3f} ({side_full}) vs "
              f"gravity-only {r['rho_grav']:.3f} ({side_grav})  "
              f"realized beta {r['beta_real']:.3f}  {r['verdict']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
