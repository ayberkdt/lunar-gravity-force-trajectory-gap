"""Aggregate + LaTeX + descriptives for the Atallah benchmark (R12).

Reads r12_atallah_campaign.json (accuracy comparisons) and the per-trajectory
sidecars (for the cost angle: mean <N^2> and measured gravity-kernel time), then
emits a booktabs table and a descriptives JSON. The cost angle is essential: the
perilune-tolerance-matched Atallah rule is more accurate than the critical fixed
degree, but its conservative bound over-provisions degree, so the comparison
must be read together with the work it spends.
"""
from __future__ import annotations

import json
import math
import os
from pathlib import Path

import numpy as np

METRICS = Path(__file__).resolve().parents[1] / "metrics"
_POP = os.environ.get("R12_POPULATION", "A").upper()
if _POP == "B":
    CAMPAIGN = METRICS / "r12_atallah_campaign_designB.json"
    R12_CASE = METRICS / "r12_cases" / "atallah_designB"
    R11_CASE = METRICS / "r11_cases" / "designB_convergence"
    _SUFFIX = "_designB"
    _LABEL = "designB-atallah-benchmark"
    _POPNAME = "independent design-B"
else:
    CAMPAIGN = METRICS / "r12_atallah_campaign.json"
    R12_CASE = METRICS / "r12_cases" / "atallah"
    R11_CASE = METRICS / "r11_cases" / "convergence"
    _SUFFIX = ""
    _LABEL = "atallah-benchmark"
    _POPNAME = "64-orbit design-A"


def _tel(base_dir: Path, index: int, policy: str, level: str = "tight"):
    p = base_dir / f"sobolA_{index:03d}" / f"{policy}_{level}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text())["telemetry"]


def cost_ratios(index: int) -> dict:
    at = _tel(R12_CASE, index, "atallah")
    fw = _tel(R12_CASE, index, "fixed_work_atallah")
    cr = _tel(R11_CASE, index, "fixed_critical")
    out = {}
    if at and cr:
        out["mean_N2_atallah"] = at.get("mean_degree_sq")
        out["mean_N2_critical"] = cr.get("mean_degree_sq")
        if cr.get("mean_degree_sq"):
            out["work_ratio_atallah_over_critical"] = (
                at["mean_degree_sq"] / cr["mean_degree_sq"])
        if cr.get("gravity_kernel_ns"):
            out["kernel_time_ratio_atallah_over_critical"] = (
                at["gravity_kernel_ns"] / cr["gravity_kernel_ns"])
        out["atallah_mean_degree"] = at.get("mean_degree")
    if at and fw:
        out["n_work_atallah"] = int(round(math.sqrt(at["mean_degree_sq"])))
    return out


def stat(vals):
    a = np.asarray([v for v in vals if v is not None and np.isfinite(v)])
    if a.size == 0:
        return None
    return {"n": int(a.size), "median": float(np.median(a)),
            "p10": float(np.percentile(a, 10)), "p90": float(np.percentile(a, 90)),
            "min": float(a.min()), "max": float(a.max())}


def build():
    d = json.loads(CAMPAIGN.read_text())
    rows = d["rows"]
    dec = d["summary"]["decisions"]
    costs = {r["sobol_index"]: cost_ratios(r["sobol_index"]) for r in rows}
    work_ratio = stat([costs[r["sobol_index"]].get("work_ratio_atallah_over_critical")
                       for r in rows])
    kt_ratio = stat([costs[r["sobol_index"]].get("kernel_time_ratio_atallah_over_critical")
                     for r in rows])

    desc = {"orbits": len(rows), "decisions": dec,
            "cost_vs_critical": {"work_ratio_mean_N2": work_ratio,
                                 "kernel_time_ratio": kt_ratio},
            "per_orbit_cost": costs}
    (METRICS / f"r12_atallah_descriptives{_SUFFIX}.json").write_text(
        json.dumps(desc, indent=2), encoding="utf-8")

    dc = dec["atallah_vs_fixed_critical"]
    dw = dec["atallah_vs_fixed_work_atallah"]

    def rho_cell(x):
        r = x["rho"]
        return (f"{r['median']:.2f} [{r['p10']:.2f}, {r['p90']:.2f}]"
                if r else "--")

    wr = (f"{work_ratio['median']:.2f} [{work_ratio['p10']:.2f}, "
          f"{work_ratio['p90']:.2f}]") if work_ratio else "--"
    tex = f"""% auto-generated by rev12_atallah_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\caption{{Direct Atallah radial-adaptive benchmark on the {_POPNAME}
  set, perilune-tolerance matched to the critical fixed degree's perilune
  error target and applied
  on the same 10-km altitude bins as the other schedules. Errors are seven-day
  position RMS against the same-tolerance reference; a comparison is resolved by the
  reference-inclusive envelope rule. $\\rho>1$ favors Atallah. The last row is
  Atallah's mean $\\langle N^2\\rangle$ relative to the critical fixed degree, the
  work its conservative bound spends for its accuracy.}}
  \\label{{tab:{_LABEL}}}
  \\begin{{tabular}}{{l r r r r r}}
    \\toprule
    comparison & pairs & resolved & Atallah wins & fixed wins & $\\rho$ median [p10, p90]\\\\
    \\midrule
    vs critical-altitude fixed & {dc['pairs']} & {dc['resolved']} & {dc['resolved_atallah_wins']} & {dc['resolved_fixed_wins']} & {rho_cell(dc)}\\\\
    vs work-matched fixed & {dw['pairs']} & {dw['resolved']} & {dw['resolved_atallah_wins']} & {dw['resolved_fixed_wins']} & {rho_cell(dw)}\\\\
    \\midrule
    \\multicolumn{{6}}{{l}}{{Atallah work $\\langle N^2\\rangle$ relative to critical fixed degree: {wr}}}\\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""
    (METRICS / f"r12_atallah_benchmark_table{_SUFFIX}.tex").write_text(
        tex, encoding="utf-8")
    print(f"[written] r12_atallah_benchmark_table{_SUFFIX}.tex, "
          f"r12_atallah_descriptives{_SUFFIX}.json")
    print(f"  vs critical: resolved {dc['resolved']}/{dc['pairs']}, "
          f"Atallah wins {dc['resolved_atallah_wins']}")
    print(f"  vs work-matched: resolved {dw['resolved']}/{dw['pairs']}, "
          f"Atallah wins {dw['resolved_atallah_wins']}, unresolved {dw['unresolved']}")
    if work_ratio:
        print(f"  Atallah work vs critical: median {work_ratio['median']:.2f}x")


def _fmt(s, digits=2):
    return "--" if not s else (f"{s['median']:.{digits}f} "
                               f"[{s['p10']:.{digits}f}, {s['p90']:.{digits}f}]")


def _sci1(v):
    if v is None:
        return "--"
    e = int(math.floor(math.log10(abs(v))))
    return f"${v / 10.0**e:.1f}\\times 10^{{{e}}}$"


def combined():
    """Both designs in one main-text table, with the matching record that
    makes the perilune-tolerance match auditable (degrees actually selected,
    accuracy actually delivered, work actually spent)."""
    desc = {d: json.loads((METRICS / f"r12_atallah_descriptives{sfx}.json").read_text())
            for d, sfx in (("A", ""), ("B", "_designB"))}
    tr = json.loads((METRICS / "r12_atallah_transparency.json").read_text())["designs"]

    def row(d, key, label):
        x = desc[d]["decisions"][key]
        r = x["rho"]
        rho = f"{r['median']:.2f} [{r['p10']:.2f}, {r['p90']:.2f}]" if r else "--"
        return (f"    {d} & {label} & {x['resolved']}/{x['pairs']} & "
                f"{x['resolved_atallah_wins']} & {x['resolved_fixed_wins']} & {rho}\\\\")

    lines = []
    for d in ("A", "B"):
        lines.append(row(d, "atallah_vs_fixed_critical", "critical-altitude fixed"))
        lines.append(row(d, "atallah_vs_fixed_work_atallah", "work-matched fixed"))
    body = "\n".join(lines)

    def mrow(d):
        s = tr[d]["summary"]
        return (f"    {d} & {_fmt(s['n_critical'], 0)} & "
                f"{_fmt(s['n_atallah_perilune'], 0)} & "
                f"{_sci1(s['actual_error_ratio']['median'])} & "
                f"{_fmt(s['work_ratio'])} & "
                f"{s['orbits_with_any_cap_contact']}/{s['orbits']}\\\\")

    matching = "\n".join(mrow(d) for d in ("A", "B"))
    tex = f"""% auto-generated by rev12_atallah_tables.py (combined) -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\setlength{{\\tabcolsep}}{{4.5pt}}
  \\caption{{Direct benchmark of the published Atallah radial-adaptive rule
  \\citep{{atallah2022radial}} on both 64-orbit designs, at the
  perilune-matched error target. The lower panel records what that match
  produces at perilune.}}
  \\label{{tab:atallah-benchmark}}
  \\begin{{tabular}}{{l l r r r r}}
    \\toprule
    Design & Comparator & resolved & Atallah wins & fixed wins
      & $\\rho$ median [p10, p90]\\\\
    \\midrule
{body}
    \\midrule
    \\multicolumn{{6}}{{l}}{{\\emph{{Matching record at perilune}}}}\\\\
    Design & $N_{{\\mathrm{{crit}}}}$ & $N_{{\\mathrm{{At}}}}(r_p)$ &
      target/delivered & $\\langle N^2\\rangle_{{\\mathrm{{At}}}}/N_{{\\mathrm{{crit}}}}^2$
      & cap contact\\\\
    \\midrule
{matching}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""
    (METRICS / "r12_atallah_combined_table.tex").write_text(tex, encoding="utf-8")
    print("[written] r12_atallah_combined_table.tex")


if __name__ == "__main__":
    import sys
    if "--combined" in sys.argv:
        combined()
    else:
        build()
