"""The R38 table: the operational elliptical endpoint comparison, with and
without the degree ceiling, decomposed by whether the ceiling bound.

Nothing here is retyped. Every number is read from the two campaigns' own
trajectory records and from the parent's calibration, which is also what decides
the decomposition: an orbit is "at the ceiling" when the capped run's calibrated
schedule reached the reference degree somewhere on its arc.

Usage:  python rev38_tables.py
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

KEY, PARENT_KEY = "OEU", "OE"
BETAS = ("1.00", "0.75", "0.50")
DECOMPOSED = ("1.00", "0.75")


def rows_of(key: str, beta: str) -> dict:
    p = METRICS / f"r14_trajectory_{key}_beta_{beta}.json"
    return {r["sobol_index"]: r for r in
            json.loads(p.read_text(encoding="utf-8"))["rows"]}


def ceiling_orbits(beta: str) -> set:
    p = METRICS / "r31_budget_pareto_operational_elliptical.json"
    d = json.loads(p.read_text(encoding="utf-8"))["designs"][PARENT_KEY]["rows"]
    return {r["sobol_index"] for r in d
            if r["budgets"][f"beta_{beta}"]["atallah"]["allocation"][
                "fraction_at_cap"] > 0.0}


def block(rows: dict, idxs) -> dict:
    idxs = sorted(idxs)
    a = f = u = 0
    rho = []
    for i in idxs:
        c = rows[i]["comparison"]
        if c["rho_budget"] is not None:
            rho.append(c["rho_budget"])
        if not c["resolved"]:
            u += 1
        elif c["resolved_winner"] == "atallah":
            a += 1
        else:
            f += 1
    work = [rows[i]["cost"]["total_work_ratio_atallah_over_fixed"] for i in idxs]
    return {"a": a, "f": f, "u": u, "n": len(idxs),
            "rho": st.median(rho) if rho else None,
            "work": st.median(work)}


def fmt_rho(x) -> str:
    if x is None:
        return "---"
    if x >= 100:
        return f"${x:.0f}$"
    if x >= 10:
        return f"${x:.1f}$"
    return f"${x:.2f}$"


def line(label: str, b: dict) -> str:
    return (f"    {label} & {b['a']}--{b['f']} & {b['u']} & {b['n']} & "
            f"{fmt_rho(b['rho'])} & ${b['work']:.3f}$ \\\\\n")


def main() -> int:
    out = [
        "% auto-generated by rev38_tables.py -- do not edit by hand\n",
        "  \\begin{tabular}{l r r r r r}\n",
        "    \\toprule\n",
        "    & radial--constant & unres. & $n$ & $\\rho$ & work \\\\\n",
        "    \\midrule\n",
    ]
    for beta in BETAS:
        cap, unc = rows_of(PARENT_KEY, beta), rows_of(KEY, beta)
        every = set(cap)
        touched = ceiling_orbits(beta)
        out.append(f"    \\multicolumn{{6}}{{@{{}}l}}{{\\emph{{$\\beta="
                   f"{beta}$}}}}\\\\\n")
        out.append(line("\\quad ceiling at 300, all orbits", block(cap, every)))
        out.append(line("\\quad ceiling lifted, all orbits", block(unc, every)))
        if beta in DECOMPOSED:
            out.append(line("\\quad\\quad orbits never at the ceiling, capped",
                            block(cap, every - touched)))
            out.append(line("\\quad\\quad orbits never at the ceiling, lifted",
                            block(unc, every - touched)))
            out.append(line("\\quad\\quad orbits at the ceiling, capped",
                            block(cap, touched)))
            out.append(line("\\quad\\quad orbits at the ceiling, lifted",
                            block(unc, touched)))
        if beta != BETAS[-1]:
            out.append("    \\midrule\n")
    out += ["    \\bottomrule\n", "  \\end{tabular}\n"]

    p = METRICS / "r38_uncapped_table.tex"
    p.write_text("".join(out), encoding="utf-8")
    print(f"[written] {p.name}")

    # the numbers the prose quotes, so the prose can be checked against them
    desc = {}
    for beta in BETAS:
        cap, unc = rows_of(PARENT_KEY, beta), rows_of(KEY, beta)
        every = set(cap)
        touched = ceiling_orbits(beta)
        desc[f"beta_{beta}"] = {
            "orbits_at_ceiling_in_capped_run": len(touched),
            "capped_all": block(cap, every), "uncapped_all": block(unc, every),
            "capped_never": block(cap, every - touched),
            "uncapped_never": block(unc, every - touched),
            "capped_at_ceiling": block(cap, touched),
            "uncapped_at_ceiling": block(unc, touched),
            "rho_drop_factor": (block(cap, every)["rho"]
                                / block(unc, every)["rho"]),
        }
    (METRICS / "r38_manuscript_descriptives.json").write_text(
        json.dumps({"schema": "r38_manuscript_descriptives_v1",
                    "budgets": desc}, indent=2), encoding="utf-8")
    print("[written] r38_manuscript_descriptives.json")
    for beta in BETAS:
        d = desc[f"beta_{beta}"]
        print(f"  beta {beta}: capped {d['capped_all']['a']}-"
              f"{d['capped_all']['f']} rho {d['capped_all']['rho']:.2f}  ->  "
              f"lifted {d['uncapped_all']['a']}-{d['uncapped_all']['f']} rho "
              f"{d['uncapped_all']['rho']:.2f}  (drop "
              f"{d['rho_drop_factor']:.1f}x, {d['orbits_at_ceiling_in_capped_run']} "
              f"orbits at ceiling)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
