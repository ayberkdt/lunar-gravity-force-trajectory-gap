"""R59: does the population-level verdict depend on how many orbits were drawn?

A reader is entitled to ask why 64 and not 32, and whether a different scramble
would have moved the crossing. Both questions are answerable from the archived
per-orbit rows without propagating anything new, because the design points were
drawn as a scrambled Sobol sequence and taken in index order: any leading
prefix of that sequence is itself a valid low-discrepancy sample of the same
factor box. Scoring the prefix therefore answers "what would this campaign have
concluded at n = 8, 16, 32?" exactly, not by resampling.

Two independent things are reported.

* Prefix convergence, within one design: the tally and the median error ratio
  over the first n orbits, for n = 8, 16, 32, 64.
* Between-scramble spread, at fixed n: designs A, B and C are independent
  scrambles of the same box, so the spread of their n = 64 verdicts is an
  empirical randomized-QMC uncertainty for a population-level ranking. Three
  draws is a small sample for a spread and is reported as a range, not as a
  standard error.

Nothing here re-scores an orbit. Resolution is the flag the original campaign
wrote; this driver only counts.

Usage
-----
    python rev59_design_size.py                     # A, B, C at beta = 1
    python rev59_design_size.py --designs A B C OE
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"
OUT = METRICS / "r59_design_size_convergence.json"
TABLE = METRICS / "r59_design_size_table.tex"

PREFIXES = (8, 16, 32, 64)


def load(design: str, beta: float = 1.00) -> list:
    p = METRICS / f"r14_trajectory_{design}_beta_{beta:.2f}.json"
    rows = json.loads(p.read_text(encoding="utf-8"))["rows"]
    return sorted(rows, key=lambda r: int(r["sobol_index"]))


def tally(rows: list, n: int) -> dict:
    """Count the first n orbits of the sequence as the campaign would have."""
    sub = [r for r in rows if int(r["sobol_index"]) < n]
    comp = [r["comparison"] for r in sub]
    res = [c for c in comp if c.get("resolved")]
    radial = sum(1 for c in res if c.get("resolved_winner") == "atallah")
    fixed = sum(1 for c in res if c.get("resolved_winner") == "fixed")
    rho = [c["rho_budget"] for c in comp if c.get("rho_budget")]
    return {
        "n": len(sub),
        "resolved": len(res),
        "radial_wins": radial,
        "constant_wins": fixed,
        "unresolved": len(comp) - len(res),
        "median_rho_budget": float(np.median(rho)) if rho else None,
        "constant_share_of_resolved": (fixed / len(res)) if res else None,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--designs", nargs="+", default=["A", "B", "C"])
    ap.add_argument("--beta", type=float, default=1.00)
    a = ap.parse_args()

    out = {"schema": "r59_design_size_convergence_v1",
           "beta": a.beta,
           "what_this_is": "prefix re-tally of archived rows; no orbit is "
                           "re-scored and nothing is propagated",
           "prefix_validity": "design points are a scrambled Sobol sequence "
                              "taken in index order, so a leading prefix is a "
                              "low-discrepancy sample of the same box",
           "designs": {}}

    for d in a.designs:
        try:
            rows = load(d, a.beta)
        except FileNotFoundError:
            print(f"[r59] {d}: no beta={a.beta:.2f} record, skipped")
            continue
        out["designs"][d] = {str(n): tally(rows, n) for n in PREFIXES}

    # Between-scramble spread at the full size, over whatever independent
    # coverage draws are present.
    full = {d: v[str(PREFIXES[-1])] for d, v in out["designs"].items()}
    shares = [v["constant_share_of_resolved"] for v in full.values()
              if v["constant_share_of_resolved"] is not None]
    rhos = [v["median_rho_budget"] for v in full.values()
            if v["median_rho_budget"] is not None]
    out["between_scramble_at_64"] = {
        "draws": len(shares),
        "constant_share_of_resolved": {
            "min": min(shares), "max": max(shares)} if shares else None,
        "median_rho_budget": {
            "min": min(rhos), "max": max(rhos)} if rhos else None,
        "caveat": "three draws bound a range, not a standard error",
    }

    OUT.write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(f"[r59] written {OUT.name}")

    lines = [r"% auto-generated by rev59_design_size.py -- do not edit by hand",
             r"\begin{tabular}{@{}l r r r r r@{}}", r"\toprule",
             r"design & $n$ & resolved & constant & radial & "
             r"median $\rho_{\mathrm{budget}}$\\", r"\midrule"]
    for d, per_n in out["designs"].items():
        for i, n in enumerate(PREFIXES):
            t = per_n[str(n)]
            rho = ("---" if t["median_rho_budget"] is None
                   else f"{t['median_rho_budget']:.3f}")
            lines.append(
                f"{d if i == 0 else ''} & {t['n']} & {t['resolved']} & "
                f"{t['constant_wins']} & {t['radial_wins']} & {rho}\\\\")
        if d != list(out["designs"])[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[r59] written {TABLE.name}")

    for d, per_n in out["designs"].items():
        for n in PREFIXES:
            t = per_n[str(n)]
            print(f"  {d} n={t['n']:3d}: resolved {t['resolved']:3d}, "
                  f"constant {t['constant_wins']:3d}, radial {t['radial_wins']:3d}, "
                  f"median rho = {t['median_rho_budget']}")
    b = out["between_scramble_at_64"]
    if b["constant_share_of_resolved"]:
        c = b["constant_share_of_resolved"]
        print(f"  between scrambles at n=64: constant share of resolved "
              f"{c['min']:.3f}--{c['max']:.3f} over {b['draws']} draws")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
