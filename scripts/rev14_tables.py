def force_vs_trajectory(pareto: dict, traj: dict, des: str, beta: float) -> dict:
    """How well does the noise-free force defect predict the propagated ranking?

    Two separate questions: does it pick the same winner (agreement), and does it
    order the orbits the same way (rank/log correlation). They can disagree, and
    on this campaign they do.
    """
    key = key_of(beta)
    fd = {r["sobol_index"]: r["budgets"][key]["ratios"]
          for r in pareto["designs"][des]["rows"]}
    pairs, agree, n = [], 0, 0
    for r in traj[des][beta]["rows"]:
        i = r["sobol_index"]
        if i not in fd:
            continue
        c = r["comparison"]
        ra, rho = fd[i]["R_a_defect_rms"], c["rho_budget"]
        if ra is None or rho is None or ra <= 0 or rho <= 0:
            continue
        pairs.append((ra, rho))
        if c["resolved"]:
            n += 1
            agree += (fd[i]["atallah_smaller_defect"]
                      == (c["resolved_winner"] == "atallah"))
    if not pairs:
        return {}
    a = np.log10(np.array([p[0] for p in pairs]))
    b = np.log10(np.array([p[1] for p in pairs]))
    return {
        "orbits": len(pairs), "resolved": n, "winner_agreement": agree,
        "log_correlation": float(np.corrcoef(a, b)[0, 1]) if len(a) > 2 else None,
        "median_log10_offset": float(np.median(a - b)),
        "median_force_ratio": float(np.median(10.0 ** a)),
        "median_trajectory_ratio": float(np.median(10.0 ** b)),
    }


def mechanism(pareto: dict, traj: dict, des: str, beta: float) -> dict:
    """What predicts the propagated outcome: how far the allocation spreads the
    degree, how much extra integrator work it provokes, or how often it switches?"""
    key = key_of(beta)
    al = {r["sobol_index"]: r["budgets"][key]
          for r in pareto["designs"][des]["rows"]}
    cols = {k: [] for k in ("log_rho", "degree_span", "min_over_ncrit",
                            "rhs_ratio", "total_work_ratio", "switches",
                            "eccentricity")}
    for r in traj[des][beta]["rows"]:
        i, c = r["sobol_index"], r["comparison"]
        if i not in al or not c["rho_budget"] or c["rho_budget"] <= 0:
            continue
        a = al[i]["atallah"]["allocation"]
        nc = max(int(r["n_critical"]), 1)
        cols["log_rho"].append(math.log10(c["rho_budget"]))
        cols["degree_span"].append(a["max_degree"] / max(a["min_degree"], 1))
        cols["min_over_ncrit"].append(a["min_degree"] / nc)
        cols["rhs_ratio"].append(r["cost"]["rhs_ratio_atallah_over_fixed"])
        cols["total_work_ratio"].append(r["cost"]["total_work_ratio_atallah_over_fixed"])
        cols["switches"].append(a["switch_count_binned"])
        cols["eccentricity"].append(r["design_point"]["eccentricity"])
    if len(cols["log_rho"]) < 3:
        return {}
    y = np.array(cols["log_rho"])
    out = {"orbits": len(y),
           "median_min_degree_over_ncrit": float(np.median(cols["min_over_ncrit"])),
           "median_degree_span": float(np.median(cols["degree_span"])),
           "median_rhs_ratio": float(np.median(cols["rhs_ratio"])),
           "median_total_work_ratio": float(np.median(cols["total_work_ratio"])),
           "correlations_with_log_rho": {}}
    for k, v in cols.items():
        if k == "log_rho":
            continue
        out["correlations_with_log_rho"][k] = float(
            np.corrcoef(y, np.array(v, dtype=float))[0, 1])
    return out


def load_trajectories(pareto: dict) -> dict:
    """Only the budgets this campaign's frozen calibration carries.

    The records are named by driver rather than by campaign, so the glob also
    catches budgets propagated by later campaigns against their own calibration
    (R28's post-hoc midpoint is one). Those belong to the campaign that ran them
    and are reported there; pairing one with this pareto record would raise a
    KeyError at best and index it as pre-registered at worst. Membership is
    tested against the record rather than against a list of today's budgets, so
    a budget added later is skipped without editing this.
    """
    grid = set(pareto["designs"]["A"]["summary"])
    out = {}
    for p in sorted(METRICS.glob("r14_trajectory_*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        # membership is design AND budget: later campaigns reuse this driver's
        # record naming for other designs (C, the strata), and those must not
        # be paired with this campaign's pareto record
        if d["design"] not in pareto["designs"]:
            continue
        if key_of(float(d["beta"])) not in grid:
            continue
        out.setdefault(d["design"], {})[float(d["beta"])] = d
    return out


