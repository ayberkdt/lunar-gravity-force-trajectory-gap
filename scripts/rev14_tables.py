def key_of(b):
    return f"beta_{b:.2f}"


def sci(v, digits=2):
    if v is None or not np.isfinite(v):
        return "--"
    if v == 0.0:
        return "0"
    e = int(math.floor(math.log10(abs(v))))
    return f"${v / 10.0 ** e:.{digits}f}\\times 10^{{{e}}}$"


def num(v, digits=2):
    if v is None or not np.isfinite(v):
        return "--"
    if abs(v) >= 1e4 or (abs(v) < 1e-2 and v != 0):
        return sci(v, digits)
    return f"{v:.{digits}f}"


def stat(vals):
    a = np.asarray([v for v in vals if v is not None and np.isfinite(v)], float)
    if a.size == 0:
        return None
    return {"n": int(a.size), "median": float(np.median(a)),
            "p10": float(np.percentile(a, 10)), "p90": float(np.percentile(a, 90))}


def cap_audit(pareto: dict, des: str, key: str) -> dict:
    """The radial rule's advantage is flattered wherever the calibrated degree
    reaches the adopted reference degree, since its force model is then the reference.
    This repeats each budget on the orbits that never touch the cap."""
    rows = [r for r in pareto["designs"][des]["rows"]
            if not r["budgets"][key]["censored"]]
    if not rows:
        return {"orbits": 0}
    touch = [r for r in rows
             if r["budgets"][key]["atallah"]["allocation"]["fraction_at_cap"] > 0.0]
    zero = [r for r in rows
            if r["budgets"][key]["atallah"]["defect"]["defect_rms_m_s2"] == 0.0]
    free = [r for r in rows
            if r["budgets"][key]["atallah"]["allocation"]["fraction_at_cap"] == 0.0]
    return {
        "orbits": len(rows), "cap_touching": len(touch),
        "zero_defect": len(zero),
        "max_fraction_at_cap": max(
            r["budgets"][key]["atallah"]["allocation"]["fraction_at_cap"]
            for r in rows),
        "cap_free_orbits": len(free),
        "cap_free_R_a": stat([r["budgets"][key]["ratios"]["R_a_defect_rms"]
                              for r in free]),
        "cap_free_atallah_wins": int(sum(
            r["budgets"][key]["ratios"]["atallah_smaller_defect"] for r in free)),
    }


