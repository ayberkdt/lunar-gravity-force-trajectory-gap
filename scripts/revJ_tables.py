"""Manuscript tables for the three JGCD campaigns.

Generated from the scored records, never typed. Each table is written to its
own file so that a change in one campaign does not touch the others, and every
file carries a header saying which record it came from -- the tables and the
numbers they quote have to move together or the paper drifts from its own
evidence.

Usage:
    python revJ_tables.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"


def _load(name: str) -> dict | None:
    p = METRICS / name
    if not p.is_file() or not p.stat().st_size:
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def _write(name: str, source: str, lines: list[str]) -> None:
    out = METRICS / name
    header = [f"% generated by revJ_tables.py from {source}",
              "% do not edit by hand"]
    out.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"[written] {out.name}")


def table_cross_solution() -> None:
    """Primary and cross-solution populations under one convention."""
    d = _load("rJ_field_comparison_final.json") or _load(
        "rJ_field_comparison.json")
    if not d:
        return
    lines = [r"\begin{tabular}{llrrrrr}", r"\hline",
             r"Population & Solution & $n$ & resolved & radial wins "
             r"$J_F$ & radial loses $J_X$ & reversal \\",
             r"\hline"]
    for s in d["summaries"]:
        lines.append(
            f"{s['population']} & {s['field'].replace('_', r'\_')} & "
            f"{s['orbits']} & {s['resolved']} & {s['radial_wins_force']} & "
            f"{s['radial_loses_trajectory']} & {s['reversal']} \\\\")
    lines += [r"\hline", r"\end{tabular}"]
    _write("rJ_table_cross_solution.tex", "rJ_field_comparison*.json", lines)

    # The main text wants one float carrying counts and medians together; the
    # supplement wants the two tabulars separately inside its own floats. Both
    # are emitted rather than one being rebuilt by hand from the other.
    wrapped = [
        r"\begin{table}[!htbp]", r"  \centering\small",
        r"  \setlength{\tabcolsep}{4pt}",
        r"  \caption{The budget comparison at $\beta = 1$ on two independently",
        r"  produced GRAIL gravity solutions, under one set of definitions.",
        r"  Counts and medians are over resolved comparisons;",
        r"  $\tilde{\rho}_F < 1$ means the radial allocation has the smaller",
        r"  force defect and $\tilde{\rho}_X > 1$ that it has the larger",
        r"  trajectory error. The primary-field rows are the archived",
        r"  populations re-scored with this statistic, not transcribed.}",
        r"  \label{tab:cross-solution}",
        r"  \begin{tabular}{@{}llrrrrrr@{}}", r"    \toprule",
        r"    Population & Solution & $n$ & res. & force & traj. & rev. &"
        r" $\tilde{\rho}_F$ / $\tilde{\rho}_X$ \\",
        r"    \midrule"]
    for s in d["summaries"]:
        wrapped.append(
            f"    {s['population']} & {s['field'].replace('_', r'\_')} & "
            f"{s['orbits']} & {s['resolved']} & {s['radial_wins_force']} & "
            f"{s['radial_loses_trajectory']} & {s['reversal']} & "
            f"{s['median_rho_force_resolved']:.2f} / "
            f"{s['median_rho_traj_resolved']:.1f} \\\\")
    wrapped += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    _write("rJ_table_cross_solution_wrapped.tex", "rJ_field_comparison*.json",
           wrapped)

    med = [r"\begin{tabular}{llrrrr}", r"\hline",
           r"& & \multicolumn{2}{c}{all orbits} & "
           r"\multicolumn{2}{c}{resolved only} \\",
           r"Population & Solution & $\tilde{\rho}_F$ & $\tilde{\rho}_X$ & "
           r"$\tilde{\rho}_F$ & $\tilde{\rho}_X$ \\",
           r"\hline"]
    for s in d["summaries"]:
        med.append(
            f"{s['population']} & {s['field'].replace('_', r'\_')} & "
            f"{s['median_rho_force']:.2f} & "
            f"{s['median_rho_traj']:.1f} & "
            f"{s['median_rho_force_resolved']:.2f} & "
            f"{s['median_rho_traj_resolved']:.1f} \\\\")
    med += [r"\hline", r"\end{tabular}"]
    _write("rJ_table_cross_solution_medians.tex",
           "rJ_field_comparison*.json", med)


def table_budget_ladder() -> None:
    """What each metric decides, budget by budget, on the same population.

    The two metrics are put on one ladder because the interesting thing is not
    either column but the contrast between them: the force metric changes its
    mind across the grid while the trajectory metric does not, and the budget
    where the force metric is least able to decide is not the budget where the
    trajectory penalty is smallest. Reading the two in separate tables hides
    exactly that.
    """
    rows = []
    for beta, name in ((0.50, "rJ1_score_beta_0.50.json"),
                       (0.75, "rJ1_score_beta_0.75.json"),
                       (1.00, "rJ1_score.json"),
                       (1.25, "rJ1_score_beta_1.25.json")):
        d = _load(name)
        if not d:
            continue
        c, a = d["counts"], d["aggregates"]
        res = c["resolved_tighter"]
        rows.append(
            f"{beta:.2f} & {c['orbits']} & {res} & "
            f"{c['radial_wins_force']}/{res} & "
            f"{a['median_rho_force_resolved']:.2f} & "
            f"{c['radial_loses_trajectory']}/{res} & "
            f"{a['median_rho_traj_resolved']:.1f} & "
            f"{c['reversal_orbits']} \\\\")
    if not rows:
        return
    lines = [r"\begin{tabular}{lrrrrrrr}", r"\hline",
             r"& & & \multicolumn{2}{c}{force metric} & "
             r"\multicolumn{2}{c}{trajectory metric} & \\",
             r"$\beta$ & $n$ & resolved & radial wins & $\tilde{\rho}_F$ & "
             r"radial loses & $\tilde{\rho}_X$ & reversal \\",
             r"\hline", *rows, r"\hline", r"\end{tabular}"]
    _write("rJ_table_budget_ladder.tex", "rJ1_score*.json", lines)


def table_full_dynamics() -> None:
    """Paired gravity-only against full-dynamics, at each budget and size."""
    rows = []
    for name, label in (("rJ2_score.json", "$\\beta=1$, $n=24$"),
                        ("rJ2_score_n48.json", "$\\beta=1$, $n=48$"),
                        ("rJ2_score_n64.json", "$\\beta=1$, $n=64$"),
                        ("rJ2_score_beta_0.50.json", "$\\beta=0.5$, $n=24$"),
                        ("rJ2_score_beta_0.75.json", "$\\beta=0.75$, $n=24$"),
                        ("rJ2_score_beta_1.25.json", "$\\beta=1.25$, $n=24$"),
                        ("rJ2_score_n64_designB.json",
                         "$\\beta=1$, design B, $n=64$"),
                        ("rJ2_score_n64_recal.json",
                         "$\\beta=1$, recalibrated, $n=64$"),
                        ("rJ2_score_am0.08.json",
                         "$\\beta=1$, $A/m \\times 8$, $n=24$")):
        d = _load(name)
        if not d:
            continue
        c, a = d["counts"], d["aggregates"]
        rows.append(
            f"{label} & {c['orbits']} & {c['resolved_tighter']} & "
            f"{c.get('resolved_in_both_dynamics', '--')} & "
            f"{c.get('sign_agrees_resolved_in_both', '--')} & "
            f"{c['reversal_orbits']} & {a['median_rho_force']:.2f} & "
            f"{a['median_rho_traj']:.1f} \\\\")
    if not rows:
        return
    lines = [r"\begin{tabular}{lrrrrrrr}", r"\hline",
             r"Case & $n$ & resolved & resolved in both & sign agrees & "
             r"reversal & $\tilde{\rho}_F$ & $\tilde{\rho}_X$ \\",
             r"\hline", *rows, r"\hline", r"\end{tabular}"]
    _write("rJ_table_full_dynamics.tex", "rJ2_score*.json", lines)


def table_tolerance() -> None:
    """The resolution rule re-applied on each adjacent pair of levels."""
    for suffix, tag in (("", "A"), ("_designB", "B")):
        d = _load(f"rJ3_score{suffix}.json")
        if not d:
            continue
        cond = d.get("conditional_on_resolution")
        if not cond:
            continue
        pairs = cond["resolution_rule_applied_to_each_adjacent_level_pair"]
        names = {"loose_tight": r"$10^{-11}$--$10^{-12}$",
                 "tight_tighter": r"$10^{-12}$--$10^{-13}$",
                 "tighter_tightest": r"$10^{-13}$--$2.5\times10^{-14}$"}
        lines = [r"\begin{tabular}{lrrr}", r"\hline",
                 r"Level pair ($r_{\mathrm{tol}}$) & resolved & radial worse "
                 r"& $\tilde{\rho}$ \\", r"\hline"]
        for key, label in names.items():
            v = pairs.get(key)
            if not v:
                continue
            marker = r"$^{\dagger}$" if key == "tight_tighter" else ""
            lines.append(
                f"{label}{marker} & {v['resolved']}/{v['of']} & "
                f"{v['radial_worse_among_resolved']} & "
                f"{v['median_rho']:.2f} \\\\")
        lines += [r"\hline", r"\end{tabular}"]
        _write(f"rJ_table_tolerance_design{tag}.tex",
               f"rJ3_score{suffix}.json", lines)

        strata = cond["by_margin_stratum"]
        sl = [r"\begin{tabular}{lrrr}", r"\hline",
              r"Margin stratum & $n$ & sign stable at all four levels & "
              r"median $M_{\mathrm{res}}$ \\", r"\hline"]
        for role in ("high", "boundary", "low"):
            v = strata.get(role)
            if not v:
                continue
            sl.append(f"{role} & {v['orbits']} & "
                      f"{v['sign_stable_across_all_levels']} & "
                      f"{v['median_M_res_archived']:.2f} \\\\")
        sl += [r"\hline", r"\end{tabular}"]
        _write(f"rJ_table_tolerance_strata_design{tag}.tex",
               f"rJ3_score{suffix}.json", sl)


def table_budget_grid() -> None:
    """Force-metric ranking against budget on the cross-solution field."""
    d = _load("rJ1_budget_pareto.json")
    if not d:
        return
    lines = [r"\begin{tabular}{lrrrr}", r"\hline",
             r"$\beta$ & uncensored & radial wins $J_F$ & "
             r"$\tilde{\rho}_F$ (mean) & $\tilde{\rho}_F$ (RMS) \\",
             r"\hline"]
    for beta in d["budget_grid"]:
        s = d["summary"].get(f"beta_{beta:.2f}")
        if not s:
            continue
        lines.append(
            f"{beta:.2f} & {s['orbits_uncensored']} & "
            f"{s['radial_wins_force']} & {s['median_rho_force_mean']:.3f} & "
            f"{s['median_rho_force_rms']:.3f} \\\\")
    lines += [r"\hline", r"\end{tabular}"]
    _write("rJ_table_budget_grid_crossfield.tex", "rJ1_budget_pareto.json",
           lines)


def table_budget_grid_both() -> None:
    """The budget dependence of the force ranking, on both solutions.

    This is what the cross-solution claim really rests on: not the sign at one
    chosen budget, but whether the whole curve of ranking against budget is the
    same on an independently produced coefficient set. Both columns are
    computed with the campaign's statistic on each field's own reference
    trajectories, so the two are read like with like rather than across two
    published summaries.
    """
    prim = _load("rJ_budget_grid_primary.json")
    cross = _load("rJ1_budget_pareto.json")
    if not prim or not cross:
        return
    n_prim = prim["counts"]["orbits"]
    n_cross = len(cross["rows"])
    head = (r"& \multicolumn{2}{c}{JGGRX\_1800F ($n=" + str(n_prim)
            + r"$)} & \multicolumn{2}{c}{GRGM1200A ($n=" + str(n_cross)
            + r"$)} \\")
    lines = [r"\begin{tabular}{lrrrr}", r"\hline", head,
             r"$\beta$ & wins/uncens. & $\tilde{\rho}_F$ & "
             r"wins/uncens. & $\tilde{\rho}_F$ \\", r"\hline"]
    for beta in prim["budget_grid"]:
        key = f"beta_{beta:.2f}"
        a = prim["summary_pooled"].get(key)
        b = cross["summary"].get(key)
        if not a:
            continue
        cells = (f"{a['radial_wins_force']}/{a['orbits_uncensored']} & "
                 f"{a['median_rho_force_mean']:.3f} & ")
        cells += (f"{b['radial_wins_force']}/{b['orbits_uncensored']} & "
                  f"{b['median_rho_force_mean']:.3f}" if b else "-- & --")
        lines.append(f"{beta:.2f} & {cells} \\\\")
    lines += [r"\hline", r"\end{tabular}"]
    _write("rJ_table_budget_grid_both.tex",
           "rJ_budget_grid_primary.json + rJ1_budget_pareto.json", lines)


def table_fidelity() -> None:
    d = _load("rJ_fidelity_check.json")
    if not d:
        return
    c = d["counts"]
    lines = [r"\begin{tabular}{lr}", r"\hline",
             r"Archived cases recomputed & " f"{c['recomputed']}" r" \\",
             r"Matching the archived record & " f"{c['matched']}" r" \\",
             r"Maximum relative deviation & "
             f"{d['max_relative_deviation']:.1e}" r" \\",
             r"\hline", r"\end{tabular}"]
    _write("rJ_table_fidelity.tex", "rJ_fidelity_check.json", lines)


def numbers() -> None:
    """Every number the prose quotes, as macros.

    The campaigns grow: the cross-solution population doubles, the
    full-dynamics one goes from a subset to two whole designs. Typing their
    counts into the text would guarantee that some of them are stale by the
    time the paper is read, and a stale count is worse than no count. So the
    text quotes macros and this file defines them from the scored records --
    including which population the macro came from, because "48 orbits" and
    "64 orbits" are different claims and the reader is told which one is being
    made.
    """
    out: list[str] = []

    def put(name: str, value) -> None:
        out.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    fid = _load("rJ_fidelity_check.json")
    if fid:
        put("JfidCases", fid["counts"]["recomputed"])
        put("JfidMatched", fid["counts"]["matched"])
        put("JfidMaxDev", f"{fid['max_relative_deviation']:.0e}"
            if fid["max_relative_deviation"] else "0")

    cal = _load("rJ1_field_calibration.json")
    if cal:
        put("JcrossField", "GRGM1200A")
        put("JcrossPfit", f"{cal['p_fit']:.3f}")
        put("JcrossPsafe", f"{cal['p_safe']:.3f}")

    j1 = _load("rJ1_score.json")
    if j1:
        c, a = j1["counts"], j1["aggregates"]
        put("JcrossOrbits", c["orbits"])
        put("JcrossResolved", c["resolved_tighter"])
        put("JcrossForceWins", c["radial_wins_force"])
        put("JcrossTrajLoses", c["radial_loses_trajectory"])
        put("JcrossReversal", c["reversal_orbits"])
        put("JcrossRhoFall", f"{a['median_rho_force']:.2f}")
        put("JcrossRhoXall", f"{a['median_rho_traj']:.1f}")
        put("JcrossRhoF", f"{a['median_rho_force_resolved']:.2f}")
        put("JcrossRhoX", f"{a['median_rho_traj_resolved']:.1f}")
        put("JcrossWorkMismatch", f"{100 * a['max_work_mismatch']:.1f}")

    # The largest completed full-dynamics population is the one worth quoting.
    for name in ("rJ2_score_n64.json", "rJ2_score_n48.json",
                 "rJ2_score.json"):
        j2 = _load(name)
        if not j2:
            continue
        c, a = j2["counts"], j2["aggregates"]
        put("JfullOrbits", c["orbits"])
        put("JfullResolved", c["resolved_tighter"])
        put("JfullBothResolved", c.get("resolved_in_both_dynamics", "--"))
        put("JfullSignAgree", c.get("sign_agrees_resolved_in_both", "--"))
        put("JfullReversal", c["reversal_orbits"])
        put("JfullRhoF", f"{a['median_rho_force']:.2f}")
        put("JfullRhoX", f"{a['median_rho_traj']:.1f}")
        put("JfullRhoXgrav", f"{a['median_rho_traj_gravity_only']:.1f}")
        put("JfullBetaMedian", f"{a.get('median_realized_beta_radial', 0):.3f}")
        put("JfullBetaWithin",
            a.get("orbits_within_10pct_of_declared_budget", "--"))
        put("JfullBetaWorst",
            f"{a.get('max_realized_beta_deviation_radial', 0):.2f}")
        break
    if _load("rJ2_score_n64_designB.json"):
        d = _load("rJ2_score_n64_designB.json")
        put("JfullBOrbits", d["counts"]["orbits"])
        put("JfullBSignAgree",
            d["counts"].get("sign_agrees_resolved_in_both", "--"))
        put("JfullBBothResolved",
            d["counts"].get("resolved_in_both_dynamics", "--"))
        # budget adherence of the carried-over policy on design B, quoted
        # beside design A's so neither design's drift stands in for both
        ab = d["aggregates"]
        put("JfullBBetaMedian",
            f"{ab.get('median_realized_beta_radial', 0):.3f}")
        put("JfullBBetaWithin",
            ab.get("orbits_within_10pct_of_declared_budget", "--"))
        put("JfullBBetaWorst",
            f"{ab.get('max_realized_beta_deviation_radial', 0):.2f}")

    # The tolerance control runs on both archived populations; the combined
    # count is what the text quotes, so it is formed here rather than by the
    # reader adding two numbers from two tables.
    admitted = stable = 0
    for suffix in ("", "_designB"):
        rec = _load(f"rJ3_score{suffix}.json")
        cond = (rec or {}).get("conditional_on_resolution")
        if cond:
            admitted += cond["admitted_by_manuscript_pair"]
            stable += cond["of_those_sign_unchanged_in_every_pair_that_resolves"]
    if admitted:
        put("JtolBothAdmitted", admitted)
        put("JtolBothStable", stable)

    # The other arm of the full-dynamics campaign: the policy recalibrated so
    # that it actually spends the declared budget under the new dynamics. What
    # the text needs from it is that the answer did not move and that the
    # budget is now held, so both are defined.
    recal = _load("rJ2_score_n64_recal.json")
    if recal:
        c, a = recal["counts"], recal["aggregates"]
        put("JrecalOrbits", c["orbits"])
        put("JrecalBothResolved", c.get("resolved_in_both_dynamics", "--"))
        put("JrecalSignAgree", c.get("sign_agrees_resolved_in_both", "--"))
        put("JrecalReversal", c["reversal_orbits"])
        put("JrecalRhoX", f"{a['median_rho_traj']:.1f}")
        put("JrecalBetaWithin", a.get("orbits_within_10pct_of_declared_budget"))
        put("JrecalBetaWorst",
            f"{a.get('max_realized_beta_deviation_radial', 0):.3f}")

    higham = _load("rJ2_score_am0.08.json")
    if higham:
        c, a = higham["counts"], higham["aggregates"]
        put("JamOrbits", c["orbits"])
        put("JamBothResolved", c.get("resolved_in_both_dynamics", "--"))
        put("JamSignAgree", c.get("sign_agrees_resolved_in_both", "--"))
        put("JamRhoX", f"{a['median_rho_traj']:.1f}")

    j3 = _load("rJ3_score.json")
    if j3 and j3.get("conditional_on_resolution"):
        cond = j3["conditional_on_resolution"]
        put("JtolOrbits", j3["counts"]["orbits"])
        put("JtolAdmitted", cond["admitted_by_manuscript_pair"])
        put("JtolAdmittedStable",
            cond["of_those_sign_unchanged_in_every_pair_that_resolves"])
        for role in ("high", "boundary", "low"):
            v = cond["by_margin_stratum"].get(role)
            if v:
                put(f"Jtol{role.capitalize()}Stable",
                    v["sign_stable_across_all_levels"])
                put(f"Jtol{role.capitalize()}Of", v["orbits"])
        tt = cond["resolution_rule_applied_to_each_adjacent_level_pair"].get(
            "tighter_tightest")
        if tt:
            put("JtolTightestResolved", tt["resolved"])
            put("JtolTightestOf", tt["of"])
            put("JtolTightestWorse", tt["radial_worse_among_resolved"])

    # The propagated ladder at the budget where the force metric is closest to
    # undecided. Quoted in the main text, so it is defined here rather than
    # read off a table by hand.
    cross = _load("rJ1_score_beta_0.75.json")
    if cross:
        c, a = cross["counts"], cross["aggregates"]
        res = c["resolved_tighter"]
        put("JladderResolvedAtCross", res)
        put("JladderForceWinsAtCross", c["radial_wins_force"])
        put("JladderTrajLosesAtCross", c["radial_loses_trajectory"])
        put("JladderRhoFAtCross", f"{a['median_rho_force_resolved']:.2f}")
        put("JladderRhoXAtCross", f"{a['median_rho_traj_resolved']:.1f}")

    # The same ladder on the primary solution, at the crossing budget.
    prim = _load("rJ_ladder_primary.json")
    if prim:
        row = prim["summary_pooled"].get("beta_0.75")
        if row and row.get("resolved"):
            put("JprimResolvedAtCross", row["resolved"])
            put("JprimForceWinsAtCross", row["radial_wins_force"])
            put("JprimTrajLosesAtCross", row["radial_loses_trajectory"])
            put("JprimRhoFAtCross", f"{row['median_rho_force']:.2f}")
            put("JprimRhoXAtCross", f"{row['median_rho_traj']:.1f}")
            put("JprimOrbitsAtCross", row["orbits"])
        unit = prim["summary_pooled"].get("beta_1.00")
        if unit and unit.get("resolved"):
            put("JprimResolvedAtUnit", unit["resolved"])
            put("JprimTrajLosesAtUnit", unit["radial_loses_trajectory"])
            put("JprimRadialTrajWinsAtUnit",
                unit["resolved"] - unit["radial_loses_trajectory"])

    # The ladder's censor accounting: how many resolved comparisons -- and how
    # many radial-favoring ones -- the reference-degree censor removed at each
    # budget, against the archived error_tight verdicts. Quoted next to the
    # ladder so its tallies reconcile with Table
    # \ref{tab:budget-trajectory-pareto} instead of contradicting it.
    audit = _load("rJ_ladder_skip_audit.json")
    if audit:
        by = audit["censor_removed_by_budget"]
        for beta, tag in (("beta_0.75", "AtCross"), ("beta_1.00", "AtUnit")):
            b = by.get(beta)
            if b:
                put(f"JprimCensored{tag}", b["censored"])
                put(f"JprimCensorRadialRemoved{tag}", b["radial_wins_removed"])

    # The archived error_tight tallies at the same budgets, pooled over both
    # designs, for the same reconciliation sentence.
    for beta, tag in (("0.75", "AtCross"), ("1.00", "AtUnit")):
        res = wins = 0
        found = True
        for design in ("A", "B"):
            rec = _load(f"r14_trajectory_{design}_beta_{beta}.json")
            if not rec:
                found = False
                break
            s = rec["summary"]
            res += s["resolved"]
            wins += s["resolved_atallah_wins"]
        if found:
            put(f"JarchResolved{tag}", res)
            put(f"JarchRadialWins{tag}", wins)

    # The budget at which the force-metric ranking turns over, taken as the
    # grid point whose median ratio sits closest to 1.
    for name, macro in (("rJ1_budget_pareto.json", "Jxover"),
                        ("rJ_budget_grid_primary.json", "JxoverPrimary")):
        g = _load(name)
        if not g or not g.get("summary") and not g.get("summary_pooled"):
            continue
        summary = g.get("summary") or g.get("summary_pooled")
        # The crossing is reported as the bracket it falls in, not as a grid
        # point. Naming the point whose median happens to sit nearest unity
        # would make the answer depend on how finely the grid was sampled, and
        # would drift as the population grows.
        pts = sorted(((float(k.replace("beta_", "")), v)
                      for k, v in summary.items()), key=lambda kv: kv[0])
        lo = hi = None
        for (beta, v), (beta_n, v_n) in zip(pts, pts[1:]):
            if v["median_rho_force_mean"] > 1.0 >= v_n["median_rho_force_mean"]:
                lo, hi = (beta, v), (beta_n, v_n)
                break
        if lo is None:
            continue
        put(f"{macro}BetaLo", f"{lo[0]:.2f}")
        put(f"{macro}BetaHi", f"{hi[0]:.2f}")
        put(f"{macro}RhoLo", f"{lo[1]['median_rho_force_mean']:.2f}")
        put(f"{macro}RhoHi", f"{hi[1]['median_rho_force_mean']:.2f}")
        put(f"{macro}WinsLo", lo[1]["radial_wins_force"])
        put(f"{macro}OfLo", lo[1]["orbits_uncensored"])
        put(f"{macro}WinsHi", hi[1]["radial_wins_force"])
        put(f"{macro}OfHi", hi[1]["orbits_uncensored"])

    if out:
        _write("rJ_numbers.tex", "the scored campaign records", sorted(out))


