"""The three cost accountings on the fourteen-orbit timing panel.

Section VIII.B had this as a run of twelve numbers in prose, and three reviewers
in a row misread which accounting had been run for which member. The table makes
the gaps visible: a dash is a cell that was never propagated, not a null result.

Every count is recomputed here from the sealed records under the resolution rule
of Eq. (9), with the envelope taken as the sum of the two policies' own
level-to-level self-differences -- the same convention that reproduces the
30-8 and 40-6 the manuscript prints for the nominal match over all 128 orbits.

    nominal per call     r18_span_sweep_{A,B}_beta_1.00.json
    realized total work  r44_equal_work_tighter_{A,B}_beta_1.00.json  (k = 0.5)
    measured kernel time r65_timing_family.json                       (O58)

Usage:  python make_accounting_ladder_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"
OUT = METRICS / "r65_accounting_ladder_table.tex"
KS = ("0.25", "0.50", "0.75")


def panel_ids() -> set:
    d = json.loads((METRICS / "r48_interior_timing_selection.json"
                    ).read_text(encoding="utf-8"))
    out = set()
    for des, blk in d["designs"].items():
        rows = blk["orbits"] if isinstance(blk, dict) and "orbits" in blk else blk
        for r in rows:
            out.add((des, int(r["sobol_index"] if isinstance(r, dict) else r)))
    return out


def nominal(k: str, keep, only=None) -> tuple:
    i = f = u = 0
    for des in (("A", "B") if only is None else (only,)):
        d = json.loads((METRICS / f"r18_span_sweep_{des}_beta_1.00.json"
                        ).read_text(encoding="utf-8"))
        for r in (d["rows"] if "rows" in d else d):
            if keep is not None and (des, int(r["sobol_index"])) not in keep:
                continue
            e, c = r["entries"][k], r["entries"]["0.00"]
            thr = (e.get("envelope_m") or 0.0) + (c.get("envelope_m") or 0.0)
            gap = abs(c["error_m"] - e["error_m"])
            if thr > 0 and gap / thr > 1.0:
                i, f = (i + 1, f) if e["error_m"] < c["error_m"] else (i, f + 1)
            else:
                u += 1
    return i, f, u


def realized(keep, only=None) -> tuple:
    i = f = u = 0
    for des in (("A", "B") if only is None else (only,)):
        d = json.loads((METRICS / f"r44_equal_work_tighter_{des}_beta_1.00.json"
                        ).read_text(encoding="utf-8"))
        for r in (d["rows"] if "rows" in d else d):
            if keep is not None and (des, int(r["sobol_index"])) not in keep:
                continue
            if not r.get("resolved"):
                u += 1
            elif r.get("winner") in ("interior", "member"):
                i += 1
            else:
                f += 1
    return i, f, u


def measured(k: str) -> tuple:
    d = json.loads((METRICS / "r65_timing_family.json").read_text(encoding="utf-8"))
    s = d["by_k"][k]
    return s["interior_wins"], s["fixed_wins"], s["unresolved"]


def measured_full(design: str) -> tuple | None:
    """(O60): the measured-time comparison over one whole design.

    Reported per design because the R68 registration says so; the pooled cell
    this replaces would have been the only pooled measured-time number in the
    package.
    """
    p = METRICS / "r68_timing_full_interior.json"
    if not p.exists():
        return None
    s = json.loads(p.read_text(encoding="utf-8"))["by_design"][design]
    return (s["resolved_interior_wins"], s["resolved_constant_wins"],
            s["unresolved"])


def cell(t) -> str:
    return "--" if t is None else f"{t[0]}--{t[1]} ({t[2]})"


def main() -> int:
    keep = panel_ids()
    rows = [
        ("Nominal per call", [nominal(k, keep) for k in KS],
         [nominal("0.50", None, d) for d in ("A", "B")]),
        ("Realized total work", [None, realized(keep), None],
         [realized(None, d) for d in ("A", "B")]),
        ("Measured kernel time", [measured(k) for k in KS],
         [measured_full(d) for d in ("A", "B")]),
    ]
    body = [r"\begin{tabular}{@{}l ccc cc@{}}", r"\toprule",
            r"& \multicolumn{3}{c}{Timing panel, 14 orbits}"
            r" & \multicolumn{2}{c}{Full designs, 64 each} \\",
            r"\cmidrule(lr){2-4}\cmidrule(l){5-6}",
            r"Cost accounting & $k=0.25$ & $k=0.5$ & $k=0.75$"
            r" & A, $k=0.5$ & B, $k=0.5$ \\", r"\midrule"]
    for name, panel, full in rows:
        body.append(f"{name} & " + " & ".join(cell(c) for c in panel)
                    + " & " + " & ".join(cell(c) for c in full)
                    + " \\\\")
    body += [r"\bottomrule", r"\end{tabular}"]
    OUT.write_text("% auto-generated by make_accounting_ladder_table.py\n"
                   + "\n".join(body) + "\n", encoding="utf-8")
    print(f"[written] {OUT.name}")
    for name, panel, full in rows:
        print(f"  {name:<22}" + "  ".join(f"{cell(c):>12}" for c in panel)
              + "   | " + "  ".join(cell(c) for c in full))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
