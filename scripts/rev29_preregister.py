"""R29: register the design-C propagation campaign before it runs.

R26 froze the design and wrote the outcomes (H/I/J) and the single-draw
commitment. It did not write down how the campaign gets from a frozen list of
64 points to a budget verdict, and three of those steps are registration acts
rather than mechanics:

  * the Phase-A calibration for design C does not exist and cannot be merged
    into r14_budget_pareto.json, which is sha256-pinned in three sealed
    manifests. It goes in its own record, exactly as R28 did for beta = 0.62;

  * the accuracy-target operating point that rev14_budget_pareto.worker reads
    for every orbit is an R12 artifact, and design C has no R12 campaign. It is
    regenerated here by the R12 rule into a separate tree, and the regeneration
    is checked against the archived R12 configs of designs A and B;

  * beta = 0.62 is itself a declared post-hoc extension (R28). Running it on
    design C inherits that label and does not launder it into a pre-registered
    budget.

The verdict rule is written here, before design C has propagated a single
orbit, so that the reading of the result is fixed in advance rather than chosen
once the tallies are visible.

Usage:
    python rev29_preregister.py
"""

from __future__ import annotations

import json
from pathlib import Path

import rev10_sobol_confirmatory as base

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

R26_PREREG = METRICS / "r26_preregistration.json"
R26_DESIGN = METRICS / "r26_sobolC_design_frozen.json"
R28_AMENDMENT = METRICS / "r28_calibration_amendment.json"
PARETO = METRICS / "r14_budget_pareto.json"
OUTPUT = METRICS / "r29_preregistration.json"


def main() -> int:
    r26 = json.loads(R26_PREREG.read_text(encoding="utf-8"))
    r28 = json.loads(R28_AMENDMENT.read_text(encoding="utf-8"))
    archived = json.loads(PARETO.read_text(encoding="utf-8"))

    prereg = {
        "schema": "r29_preregistration_v1",
        "created_utc": base.utc_now(),
        "campaign": ("R29: propagate the frozen design C, calibrate its budget "
                     "grid, and run the archived budget ladder on it"),
        "parent": {
            "preregistration": R26_PREREG.name,
            "preregistration_sha256": r26["preregistration_sha256"],
            "design_sha256": r26["design"]["design_sha256"],
            "design_file_sha256": base.file_hash(R26_DESIGN),
            "inherited": ("the outcomes H/I/J, the single-draw commitment, the "
                          "seed rule and the scope statement of R26 are carried "
                          "unchanged; this record adds only the steps R26 left "
                          "unwritten"),
        },
        "not_blind": ("designs A and B are already propagated and their tallies "
                      "are known. The protection is the single-draw commitment "
                      "of R26 and the verdict rule below, both fixed before any "
                      "design-C budget number exists."),
        "stages": {
            "base": {
                "driver": "rev26_designC_base.py",
                "produces": ("r26_designC_rows.json (prepass) and "
                             "r26_designC_convergence.json with the truth "
                             "trajectories and the critical-degree comparator "
                             "at both tolerance levels"),
                "unchanged": ("the prepass and convergence drivers are the ones "
                              "that produced design B, pointed at design C"),
            },
            "operating_point": {
                "driver": "rev29_designC_operating_point.py",
                "why": ("rev14_budget_pareto.worker reads the archived R12 "
                        "accuracy-target configuration of every orbit. Design C "
                        "has no R12 campaign, so the operating point is "
                        "regenerated by the R12 rule: tol = actual worst-case "
                        "acceleration truncation error of N_crit against the "
                        "adopted truth at perilune, the 10-km binned Atallah "
                        "schedule from that tol, and N_work = "
                        "round(sqrt(<N^2>)) of the tight Atallah RHS history"),
                "writes_where": ("metrics/r29_cases/atallah_designC, a new tree; "
                                 "no R12 artifact is created, moved or touched, "
                                 "so the R12 manifest partition is unaffected"),
                "reproduction_check": {
                    "what": ("the same generator is run on a subsample of "
                             "designs A and B and compared against their "
                             "archived R12 configurations"),
                    "gate": ("tol and the binned degree table are pure "
                             "functions of the design point and must reproduce "
                             "exactly, or no design-C operating point is "
                             "written"),
                    "reported_not_gated": ("N_work comes from propagation "
                                           "telemetry and the archived R12 "
                                           "campaign ran under a different "
                                           "interpreter; any disagreement is "
                                           "reported per orbit rather than "
                                           "silently accepted or hidden"),
                },
            },
            "calibration": {
                "driver": "rev29_designC_pareto.py",
                "record": "r29_budget_pareto_designC.json",
                "grid": archived["budget_grid"],
                "extra_budget": 0.62,
                "extra_budget_status": ("post hoc, inherited from "
                                        "r28_calibration_amendment.json "
                                        f"({r28['amendment_sha256'][:16]}); it is "
                                        "reported flagged as not pre-registered "
                                        "wherever it appears, exactly as the "
                                        "design A and B midpoints are"),
                "archive_untouched": ("r14_budget_pareto.json is verified "
                                      "byte-identical before and after; design C "
                                      "is never merged into it"),
                "admissibility": ("the same pass recomputes the whole frozen "
                                  "grid for designs A and B and requires exact "
                                  "equality with the archived calibration on "
                                  "every orbit and every budget. If any scalar "
                                  "differs, no design-C calibration is written."),
            },
            "ladder": {
                "drivers": ["rev14_budget_trajectory.py", "rev18_span_sweep.py",
                            "rev19_equal_total_work.py"],
                "modification": ("none. The drivers are sha256-pinned in sealed "
                                 "manifests and are called through a wrapper "
                                 "that registers design C in their design table "
                                 "and points build_specs at the design-C "
                                 "calibration record."),
                "order": [0.75, 0.50, 1.00, 0.62, 1.25, 1.50, 2.00],
                "order_rationale": ("0.75 and 0.50 are the two budgets that "
                                    "bracket the crossing on designs A and B, so "
                                    "they are propagated first: a campaign that "
                                    "runs out of time still answers the question "
                                    "it was opened for. 1.00 replicates the "
                                    "headline budget, 0.62 the declared "
                                    "midpoint, and the rest extend the curve."),
            },
        },
        "verdict_rule": {
            "per_budget": ("from r19_equal_total_work_C_beta_*.json: interior if "
                           "resolved_interior_wins > resolved_fixed_wins, "
                           "constant if resolved_fixed_wins > "
                           "resolved_interior_wins, split if equal"),
            "bracket": ("the crossing bracket of a design is (largest grid "
                        "budget with a constant verdict, smallest grid budget "
                        "with an interior verdict], over the grid budgets that "
                        "design has propagated"),
            "reference_bracket": {
                "A": [0.50, 0.75], "B": [0.50, 0.75],
                "source": ("r19_equal_total_work_{A,B}_beta_{0.50,0.75}.json: "
                           "A 18-32 then 27-15, B 20-35 then 27-19"),
            },
            "H_requires": ("design C returns a constant verdict at beta = 0.50 "
                           "and an interior verdict at beta = 0.75"),
            "I_requires": "any other resolved pair of verdicts at those budgets",
            "J_requires": ("either budget resolves too few comparisons to "
                           "produce a verdict, or the base is incomplete"),
            "not_deciding": ("the median error ratio and its distance from unity "
                             "are recorded as a secondary signature and do not "
                             "enter the verdict, which is the tally rule the "
                             "campaign has used since R19"),
            "no_averaging": ("if design C disagrees, the three designs are "
                             "reported side by side; no pooled or averaged "
                             "bracket is quoted"),
        },
        "completion_reporting": ("every quoted design-C number carries its "
                                 "completion count. A budget whose ladder is "
                                 "partially propagated is reported as partial or "
                                 "not reported, never completed by inference."),
        "prohibited": [
            "trying a second design-C seed",
            "dropping an orbit of design C after its numbers are known",
            "merging design C into r14_budget_pareto.json",
            "editing any rev*.py that a sealed manifest hashes",
            "quoting a design-C budget whose base is incomplete",
            "presenting beta = 0.62 as a pre-registered budget on any design",
        ],
    }
    prereg["preregistration_sha256"] = base.object_hash(prereg)
    base.atomic_json(OUTPUT, prereg)
    print(f"[written] {OUTPUT.name} "
          f"sha256={prereg['preregistration_sha256'][:16]}")
    print(f"  parent R26 {r26['preregistration_sha256'][:16]}, "
          f"design {r26['design']['design_sha256'][:16]}")
    print(f"  grid {archived['budget_grid']} + 0.62 (post hoc)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
