"""What the allocation choice costs at campaign scale (R2).

The paper prices one call and one arc but never says what the decision is worth
to someone running a campaign, which is where a truncation budget actually
binds. This turns the quantities already measured into that statement.

Two measured inputs, no new propagation and no new timing:

  k   seconds of single-threaded gravity-kernel time per unit of quadratic
      work, from the controlled cost-curve session of (F4): 400 repeats per
      degree on an idle machine, reported in r12_kernel_cost_curve.json as the
      pure-N^2 proxy with an 18% relative residual against the measured curve.

  W   realized total quadratic work per arc, per policy, from each orbit's own
      beta = 1 telemetry in the R14 trajectory records. This is realized work,
      not the nominal per-call budget: it already contains the extra
      right-hand-side calls a varying degree provokes.

Kernel time per arc is then k * W. The in-run gravity_kernel_ns fields are
deliberately not used: their records carry
gravity_kernel_time_comparable = false, because they were measured during
propagation rather than in the controlled session.

The table reports the constant degree and the budget-calibrated radial
endpoint at the declared budget, and scales both to campaign sizes. The point
is not that one is cheap: it is that the radial endpoint costs more and is
also the less accurate of the two, so the extra time buys nothing.

Usage:  python rev40_campaign_cost_table.py
"""

from __future__ import annotations

import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"
OUT = METRICS / "r40_campaign_cost_table.tex"
REC = METRICS / "r40_campaign_cost.json"

SCALES = [
    ("one seven-day arc", 1),
    ("one 64-orbit coverage design", 64),
    ("both designs, one budget", 128),
    ("the seven-budget grid, both designs", 128 * 7),
    ("a 1000-sample dispersion campaign", 1000),
]


def hours(sec: float) -> str:
    if sec < 90:
        return f"{sec:.0f}~s"
    if sec < 5400:
        return f"{sec / 60:.0f}~min"
    if sec < 86400 * 2:
        return f"{sec / 3600:.1f}~h"
    return f"{sec / 86400:.1f}~d"


def main() -> int:
    curve = json.loads((METRICS / "r12_kernel_cost_curve.json").read_text(
        encoding="utf-8"))
    k = curve["fit_pure_N2_proxy"]["k"]
    resid = curve["fit_pure_N2_proxy"]["rel_rms_residual"]

    fixed, radial, ratios, wins = [], [], [], {"fixed": 0, "radial": 0,
                                               "unresolved": 0}
    for d in ("A", "B"):
        p = METRICS / f"r14_trajectory_{d}_beta_1.00.json"
        for r in json.loads(p.read_text(encoding="utf-8"))["rows"]:
            c = r.get("cost") or {}
            wf = c.get("total_quadratic_work_fixed")
            wa = c.get("total_quadratic_work_atallah")
            if not (wf and wa):
                continue
            fixed.append(k * wf)
            radial.append(k * wa)
            ratios.append(wa / wf)
            cmp_ = r.get("comparison") or {}
            if not cmp_.get("resolved"):
                wins["unresolved"] += 1
            else:
                wins["fixed" if cmp_.get("resolved_winner") == "fixed"
                     else "radial"] += 1

    mf, mr = st.median(fixed), st.median(radial)
    rows = []
    for label, n in SCALES:
        rows.append((label, n, mf * n, mr * n, (mr - mf) * n))

    lines = [r"\begin{tabular}{@{}l r r r r@{}}", r"\toprule",
             (r"campaign & arcs & constant degree & radial endpoint & "
              r"extra \\"), r"\midrule"]
    for label, n, a, b, d in rows:
        lines.append(f"{label} & {n} & {hours(a)} & {hours(b)} & "
                     f"{hours(d)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.write_text("% auto-generated by rev40_campaign_cost_table.py\n"
                   + "\n".join(lines) + "\n", encoding="utf-8")

    payload = {
        "schema": "r40_campaign_cost_v1",
        "inputs": {
            "k_seconds_per_unit_quadratic_work": k,
            "k_source": "r12_kernel_cost_curve.json fit_pure_N2_proxy",
            "k_relative_rms_residual": resid,
            "work_source": "r14_trajectory_{A,B}_beta_1.00.json cost blocks",
            "note": ("in-run gravity_kernel_ns fields are not used; their "
                     "records mark gravity_kernel_time_comparable = false"),
        },
        "orbits": len(fixed),
        "per_arc_seconds": {
            "fixed_median": mf, "radial_median": mr,
            "fixed_range": [min(fixed), max(fixed)],
            "radial_range": [min(radial), max(radial)],
        },
        "realized_work_ratio": {"median": st.median(ratios),
                                "min": min(ratios), "max": max(ratios)},
        "beta1_verdicts": wins,
        "scales": [{"campaign": l, "arcs": n, "fixed_s": a, "radial_s": b,
                    "extra_s": d} for l, n, a, b, d in rows],
    }
    OUT.parent.mkdir(exist_ok=True)
    REC.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    print(f"[written] {OUT.name} and {REC.name}")
    print(f"  k = {k:.4g} s per unit quadratic work "
          f"(residual {100 * resid:.0f}%)")
    print(f"  orbits {len(fixed)}   per-arc median: fixed {mf:.1f} s, "
          f"radial {mr:.1f} s   ratio {st.median(ratios):.2f}")
    print(f"  beta=1 verdicts: {wins}")
    for label, n, a, b, d in rows:
        print(f"    {label:<38} {n:>5}  {a:9.0f}s  {b:9.0f}s  +{d:9.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
