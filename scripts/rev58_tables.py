"""Renders the R58 endpoint work-matched control as a supplement table.

The table is deliberately placed beside the nominal per-call tallies rather
than replacing them: the two matchings answer different questions, and the
point of the control is the step between them.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"
OUT = METRICS / "r58_endpoint_equal_work_table.tex"

BETAS = (0.50, 0.62, 0.75, 1.00)
POPS = (("OEU", "ceiling-free"), ("OE", "adopted reference degree"))


def cell(design: str, beta: float) -> dict | None:
    p = METRICS / f"r58_endpoint_equal_work_{design}_beta_{beta:.2f}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))["summary"]


def main() -> int:
    lines = [r"% auto-generated by rev58_tables.py -- do not edit by hand",
             r"\begin{tabular}{@{}l l r r r r r@{}}",
             r"\toprule",
             r"population & $\beta$ & orbits & resolved & radial & constant "
             r"& median $\rho$\\",
             r"\midrule"]
    for i, (design, note) in enumerate(POPS):
        first = True
        for beta in BETAS:
            s = cell(design, beta)
            if s is None:
                continue
            label = f"{design} ({note})" if first else ""
            first = False
            lines.append(
                f"{label} & {beta:.2f} & {s['orbits']} & {s['resolved']} & "
                f"{s['resolved_radial_wins']} & {s['resolved_constant_wins']} & "
                f"{s['median_rho']:.3f}\\\\")
        if i != len(POPS) - 1:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[r58] written {OUT.name}")

    # The achieved matching is the thing a reader should be able to check at a
    # glance, so it is printed here rather than buried in the records.
    for design, _ in POPS:
        for beta in BETAS:
            s = cell(design, beta)
            if s:
                w = s["achieved_work_ratio"]
                print(f"  {design} beta={beta:.2f}: achieved work ratio "
                      f"{w['median']:.4f} [{w['min']:.4f}, {w['max']:.4f}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
