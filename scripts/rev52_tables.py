#!/usr/bin/env python3
"""R52: the two identity blocks' ceiling-free ladders, side by side.

R51's table answers "what did the ceiling do to block A". This one answers the
question that table cannot: do the two independent draws of identities agree
once the ceiling is off both of them. One row per apolune level and budget,
carrying each block's tally and median ratio, with any cell where the blocks
disagree marked.

The registration commits to recording the per-block verdicts before any pooled
ceiling-free number is quoted, so the table is generated from the verdict
record rather than assembled by hand, and the macros the prose uses come from
the same pass.

Macro names are prefixed RB rather than CL so that nothing here can be
mistaken for, or silently overwrite, R51's block-A macros.

Usage:  python rev52_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"

BETAS = ["0.50", "0.62", "0.75", "1.00"]
WORDS = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four",
         5: "five", 6: "six"}


def fmt_rho(v) -> str:
    """The formatter rev51_tables uses, so the two tables round alike."""
    if v is None:
        return "--"
    if v >= 1000.0:
        e = 0
        while v >= 10.0:
            v /= 10.0
            e += 1
        return f"${v:.1f}\\times10^{{{e}}}$"
    if v >= 10.0:
        return f"${v:.0f}$"
    if v >= 1.0:
        return f"${v:.2f}$"
    return f"${v:.3f}$"


def main() -> int:
    p = METRICS / "r52_verdict.json"
    if not p.exists():
        raise SystemExit("r52_verdict.json is missing; run rev52_verdict.py "
                         "after the ladder stages land")
    v = json.loads(p.read_text(encoding="utf-8"))

    lines = [r"% generated by rev52_tables.py; do not edit",
             r"\begin{tabular}{@{}l l r r r r@{}}",
             r"\toprule",
             r"& & \multicolumn{2}{c}{block A, ceiling free}"
             r" & \multicolumn{2}{c}{block B, ceiling free} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
             r"$\beta$ & Apolune & tally & median $\rho$ & tally"
             r" & median $\rho$ \\",
             r"\midrule"]

    cells = agree = differ = 0
    for i, b in enumerate(BETAS):
        blk = v["by_budget"].get(b)
        if not blk:
            continue
        if i:
            lines.append(r"\addlinespace")
        for lvl, r in blk["levels"].items():
            u = r["uncapped"]
            a = r.get("block_a_uncapped")
            cells += 1
            mark = ""
            if a is not None:
                if r.get("agrees_with_block_a"):
                    agree += 1
                else:
                    differ += 1
                    mark = r"$^{\ast}$"
            a_tally = "--" if a is None else f"${a['radial']}$--${a['fixed']}$"
            a_rho = "--" if a is None else fmt_rho(a["median_rho"])
            lines.append(
                f"${b}$ & ${float(lvl):.0f}$~km{mark} & {a_tally} & {a_rho} & "
                f"${u['radial']}$--${u['fixed']}$ & "
                f"{fmt_rho(u['median_rho'])}" r" \\")

    lines += [r"\bottomrule", r"\end{tabular}"]
    out = METRICS / "r52_block_replication_table.tex"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Whether the pooled ceiling-free reading is licensed is a consequence of
    # the outcome class, not a separate judgement, so the macro carrying it is
    # derived here rather than typed into a sentence.
    pooled_ok = v["outcome"] in ("P_replicates", "Q_replicates_ordering_only")
    macros = {
        "RBcells": str(cells),
        "RBagree": str(agree),
        "RBdiffer": WORDS.get(differ, str(differ)),
        "RBbudgets": WORDS.get(len(v["by_budget"]), str(len(v["by_budget"]))),
        "RBoutcome": v["outcome"].split("_")[0],
        "RBpooling": ("licensed" if pooled_ok else "not licensed"),
    }
    body = ["% generated by rev52_tables.py; do not edit"]
    body += [f"\\newcommand{{\\{k}}}{{{x}}}" for k, x in macros.items()]
    (METRICS / "r52_block_replication_macros.tex").write_text(
        "\n".join(body) + "\n", encoding="utf-8")

    print(f"[written] {out.name}")
    print(f"  {cells} cells over {len(v['by_budget'])} budgets: "
          f"{agree} agree with block A, {differ} differ")
    print(f"  outcome {v['outcome']}; pooled ceiling-free reading "
          f"{macros['RBpooling']}")
    print(f"[written] r52_block_replication_macros.tex ({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
