"""Generate manuscript LaTeX fragments + a descriptives JSON from the R11 runs.

Reads the completed R11 result indices and emits booktabs table fragments and a
single ``r11_manuscript_descriptives.json`` with the exact numbers the prose
pass cites, so the coordinated manuscript update never transcribes a figure by
hand.  siunitx is broken on this machine, so all scientific notation is written
as ``$a\\times10^{b}$`` and units are plain text (see project notes).

Inputs (each optional; a missing one is skipped with a note):
  r11_full_convergence.json      -> full 64-orbit design-A vector convergence
  r11_designB_convergence.json   -> independent design-B replication
  r11_phase_sweep.json           -> 24-phase dispersion
  r11_blend_lro_vector.json      -> 28-day LRO-like blend at vector tolerance

Outputs (metrics/):
  r11_full64_convergence_table.tex
  r11_designB_convergence_table.tex
  r11_phase_sweep_table.tex
  r11_blend_vector_table.tex
  r11_manuscript_descriptives.json

Usage:  python rev11_manuscript_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

METRICS = Path(__file__).resolve().parents[1] / "metrics"

FULL = METRICS / "r11_full_convergence.json"
DESIGNB = METRICS / "r11_designB_convergence.json"
PHASE = METRICS / "r11_phase_sweep.json"
BLEND = METRICS / "r11_blend_lro_vector.json"

SCHEDULES = ("schedule_empirical", "schedule_up", "schedule_down")
COMPARATORS = ("fixed_work", "fixed_critical")
SCHED_LABEL = {"schedule_empirical": "empirical", "schedule_up": "upward",
               "schedule_down": "downward"}
COMP_LABEL = {"fixed_work": "work-matched", "fixed_critical": "critical-altitude"}


def load(path: Path):
    if not path.exists():
        print(f"[skip] {path.name} not present")
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def sci(x, digits=1):
    """LaTeX $a\\times10^{b}$ without siunitx."""
    if x is None:
        return "--"
    if x == 0:
        return "0"
    import math
    b = int(math.floor(math.log10(abs(x))))
    a = x / (10 ** b)
    return f"${a:.{digits}f}\\times10^{{{b}}}$"


def convergence_table(data, population: str, label: str, caption: str) -> str:
    """Aggregate resolved-comparison table for a full population."""
    s = data["summary"]
    dec = s["decisions"]
    rows = []
    for sched in SCHEDULES:
        for comp in COMPARATORS:
            key = f"{sched}_vs_{comp}"
            d = dec[key]
            rho = d["rho"]
            rows.append(
                f"    {SCHED_LABEL[sched]} vs {COMP_LABEL[comp]} & "
                f"{d['pairs']} & {d['raw_schedule_wins']} & "
                f"{d['resolved']} & {d['resolved_schedule_wins']} & "
                f"{d['resolved_fixed_wins']} & {d['unresolved']} & "
                f"{rho['median']:.3f} & {rho['p10']:.3f} & {rho['p90']:.3f}\\\\")
    body = "\n".join(rows)
    n = len(data["rows"])
    tsd = s["truth_self_difference_rms_m"]
    return f"""% auto-generated by rev11_manuscript_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\caption{{{caption}}}
  \\label{{tab:{label}}}
  \\begin{{tabular}}{{l r r r r r r r r r}}
    \\toprule
    & & raw & \\multicolumn{{4}}{{c}}{{resolved}} & \\multicolumn{{3}}{{c}}{{$\\rho$}}\\\\
    \\cmidrule(lr){{4-7}}\\cmidrule(lr){{8-10}}
    comparison & pairs & sched & total & sched & fixed & unres.\\ & median & p10 & p90\\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
% {population}: {n} orbits; truth self-difference median {tsd['median']:.3f} m,
% p90 {tsd['p90']:.3f} m, max {tsd['max']:.3f} m.
"""


def per_orbit_table(data, label: str, caption: str) -> str:
    """Per-orbit errors, numerical envelope, and the two pairwise decisions.

    Emitted as a longtable so all 64 rows are traceable in the supplement.
    """
    verdict = {"schedule_empirical": "S", None: "U"}
    rows = []
    for r in sorted(data["rows"], key=lambda x: x["sobol_index"]):
        p = r["policies"]
        e_emp = p["schedule_empirical"]["errors_against_same_tolerance_truth"]["tight"]["pos_rms_m"]
        e_wrk = p["fixed_work"]["errors_against_same_tolerance_truth"]["tight"]["pos_rms_m"]
        e_crt = p["fixed_critical"]["errors_against_same_tolerance_truth"]["tight"]["pos_rms_m"]
        env = p["schedule_empirical"]["truth_inclusive_envelope_m"]
        cw = r["comparisons"]["schedule_empirical_vs_fixed_work"]
        cc = r["comparisons"]["schedule_empirical_vs_fixed_critical"]
        vw = verdict.get(cw["winner_if_resolved"], "F")
        vc = verdict.get(cc["winner_if_resolved"], "F")
        rows.append(
            f"    {r['sobol_index']} & {r['adopted_truth_degree']} & "
            f"{r['design_point']['hp_km']:.1f} & {r['n_work']} & "
            f"{r['n_critical']} & {e_emp:.2f} & {e_wrk:.2f} & {e_crt:.2f} & "
            f"{env:.3f} & {vw} & {vc}\\\\")
    body = "\n".join(rows)
    return f"""% auto-generated by rev11_manuscript_tables.py -- do not edit by hand
\\begingroup\\scriptsize\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{longtable}}{{r r r r r r r r r c c}}
\\caption{{{caption}}}\\label{{tab:{label}}}\\\\
\\toprule
idx & $N_t$ & $h_p$ & $N_w$ & $N_c$ & $E_{{\\rm emp}}$ & $E_{{\\rm work}}$
 & $E_{{\\rm crit}}$ & env. & w & c\\\\
\\midrule
\\endfirsthead
\\toprule
idx & $N_t$ & $h_p$ & $N_w$ & $N_c$ & $E_{{\\rm emp}}$ & $E_{{\\rm work}}$
 & $E_{{\\rm crit}}$ & env. & w & c\\\\
\\midrule
\\endhead
\\bottomrule
\\endfoot
{body}
\\end{{longtable}}
\\endgroup
"""


def phase_table(data) -> str:
    s = data["summary"]
    order = ("sched_down", "sched_up", "fixed_106")
    lab = {"sched_down": "downward schedule", "sched_up": "upward schedule",
           "fixed_106": "fixed $N=106$"}
    rows = []
    ebp = s["error_by_policy_m"]
    for p in order:
        pen = s["penalty_vs_fixed_138"][p]
        r = pen["ratio"]
        e = ebp[p]
        rows.append(
            f"    {lab[p]} & {e['median']:.2f} & {e['min']:.2f}--{e['max']:.2f} & "
            f"{r['median']:.1f} & {r['min']:.1f}--{r['max']:.1f} & "
            f"{pen['resolved']}/{pen['resolved']+pen['unresolved']} & "
            f"{pen['resolved_fixed138_wins']}\\\\")
    body = "\n".join(rows)
    tsd = s["truth_self_difference_rms_m"]
    e138 = ebp["fixed_138"]
    return f"""% auto-generated by rev11_manuscript_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\caption{{Initial-phase dispersion of the seven-day $50\\times300$~km polar
  scheduling penalty at position/velocity-split vector tolerance, over
  {len(data['rows'])} initial true anomalies.  Errors are position RMS against
  each phase's own $N=300$ reference; the penalty is relative to fixed
  $N=138$ (median error {e138['median']:.2f}~m).  A comparison is resolved when
  the error gap exceeds the summed truth-inclusive envelopes.}}
  \\label{{tab:phase-sweep-vector}}
  \\begin{{tabular}}{{l r r r r r r}}
    \\toprule
    & \\multicolumn{{2}}{{c}}{{error (m)}}
      & \\multicolumn{{2}}{{c}}{{penalty vs $N=138$}} & & fixed\\\\
    \\cmidrule(lr){{2-3}}\\cmidrule(lr){{4-5}}
    policy & median & range & median & range & resolved & wins\\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
% phase truth self-difference median {tsd['median']:.3f} m, max {tsd['max']:.3f} m.
"""


def blend_table(data) -> str:
    s = data["summary"]
    pol = s["policies"]
    fx = pol["fixed_N120"]["error_against_same_tolerance_truth"]["baseline"]["pos_rms_m"]
    bl = pol["corrected_blend"]["error_against_same_tolerance_truth"]["baseline"]["pos_rms_m"]
    c = s["comparison"]
    ref = s.get("r10_scalar_comparison_for_reference", {})
    winner = {"fixed_N120": "fixed $N=120$",
              "corrected_blend": "corrected blend",
              None: "unresolved"}.get(c["winner_if_resolved"],
                                      "fixed $N=120$")
    return f"""% auto-generated by rev11_manuscript_tables.py -- do not edit by hand
\\begin{{table}}[!htbp]
  \\centering\\small
  \\caption{{28-day LRO-like ($30\\times216$~km polar) fixed-degree versus
  corrected-blend comparison at position/velocity-split vector tolerance.  The
  truth self-difference falls to {s['truth_self_difference_rms_m']:.2f}~m, so
  the previously ambiguous ordering resolves.}}
  \\label{{tab:blend-vector}}
  \\begin{{tabular}}{{l r r r}}
    \\toprule
    & error (m) & self-diff (m) & truth-incl.\\ env.\\ (m)\\\\
    \\midrule
    fixed $N=120$ & {fx:.1f} & {pol['fixed_N120']['self_difference_rms_m']:.2f}
      & {pol['fixed_N120']['truth_inclusive_envelope_m']:.2f}\\\\
    corrected blend & {bl:.1f}
      & {pol['corrected_blend']['self_difference_rms_m']:.2f}
      & {pol['corrected_blend']['truth_inclusive_envelope_m']:.2f}\\\\
    \\midrule
    \\multicolumn{{4}}{{l}}{{gap {c['absolute_baseline_error_difference_m']:.1f}~m,
      threshold {c['resolution_threshold_m']:.1f}~m, resolved:
      {'yes' if c['resolved'] else 'no'} ({winner})}}\\\\
    \\multicolumn{{4}}{{l}}{{scalar-tolerance reference: gap
      {ref.get('absolute_baseline_error_difference_m','--')}~m, threshold
      {ref.get('resolution_threshold_m','--')}~m, unresolved}}\\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""


def main() -> int:
    desc = {}

    full = load(FULL)
    if full:
        (METRICS / "r11_full64_convergence_table.tex").write_text(
            convergence_table(
                full, "design-A", "full64-convergence",
                "Full 64-orbit design-A comparison at position/velocity-split "
                "vector tolerance.  All 64 orbits were rerun under the "
                "vector-tolerance contract and each comparison is decided "
                "individually; the resolved and unresolved counts are given "
                "per row.  $\\rho>1$ favors the schedule."),
            encoding="utf-8")
        desc["full64"] = full["summary"]
        print("[written] r11_full64_convergence_table.tex")
        (METRICS / "r11_full64_per_orbit_table.tex").write_text(
            per_orbit_table(
                full, "full64-per-orbit",
                "Per-orbit design-A vector-tolerance results. $N_t$ is the "
                "adopted truth degree, $h_p$ the perilune altitude (km), "
                "$N_w$ and $N_c$ the work-matched and critical-altitude "
                "degrees, and $E$ the seven-day position RMS (m) against the "
                "same-tolerance truth. `env.' is the truth-inclusive numerical "
                "envelope (m) of the empirical schedule. Columns w and c give "
                "the work-matched and critical-altitude decisions: S schedule, "
                "F fixed degree, U unresolved."),
            encoding="utf-8")
        print("[written] r11_full64_per_orbit_table.tex")

    db = load(DESIGNB)
    if db and db.get("rows"):
        n = len(db["rows"])
        if db.get("complete"):
            scope = "64-orbit scrambled-Sobol coverage design, seed 20260724"
            partial = ""
        else:
            scope = (f"{n} of 64 orbits of a scrambled-Sobol coverage design, "
                     "seed 20260724")
            partial = (f" This is the {n}-orbit subset completed within the "
                       "compute window; the remaining orbits are pending.")
        (METRICS / "r11_designB_convergence_table.tex").write_text(
            convergence_table(
                db, "design-B", "designB-convergence",
                f"Independent design-B replication ({scope}) at the same "
                "vector tolerance." + partial),
            encoding="utf-8")
        desc["designB"] = db["summary"]
        print(f"[written] r11_designB_convergence_table.tex ({n} orbits, "
              f"complete={db.get('complete')})")
        (METRICS / "r11_designB_per_orbit_table.tex").write_text(
            per_orbit_table(
                db, "designB-per-orbit",
                "Per-orbit design-B vector-tolerance results, columns as in "
                "the design-A per-orbit table."),
            encoding="utf-8")
        print("[written] r11_designB_per_orbit_table.tex")

    phase = load(PHASE)
    if phase:
        (METRICS / "r11_phase_sweep_table.tex").write_text(
            phase_table(phase), encoding="utf-8")
        desc["phase"] = phase["summary"]
        print("[written] r11_phase_sweep_table.tex")

    blend = load(BLEND)
    if blend and blend.get("summary"):
        (METRICS / "r11_blend_vector_table.tex").write_text(
            blend_table(blend), encoding="utf-8")
        desc["blend"] = blend["summary"]
        print("[written] r11_blend_vector_table.tex")

    (METRICS / "r11_manuscript_descriptives.json").write_text(
        json.dumps(desc, indent=2), encoding="utf-8")
    print("[written] r11_manuscript_descriptives.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
