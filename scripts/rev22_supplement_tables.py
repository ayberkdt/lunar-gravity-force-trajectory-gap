"""Two supplementary tables built from archived records only (R22).

Nothing is propagated here. The script reads the frozen R18 span-sweep records
and the R20 sixty-day sidecars and emits:

  1. the by-$k$ aggregate of the continuation family at every declared budget,
     so the two budgets that the main text reports only through their best
     member are visible member by member;

  2. the per-orbit sixty-day record of the family, with the realized cost
     columns that decide whether a seven-day-calibrated degree table still
     spends the declared budget over a sixty-day arc.

The second table answers a question the seven-day calibration cannot: the
budget was matched on the seven-day reference epochs, and an orbit whose
altitude dwell changes over sixty days need not still spend it.

Usage:
    python rev22_supplement_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
METRICS = ROOT / "metrics"
CASES = METRICS / "r20_cases"
K_ALL = ("0.00", "0.25", "0.50", "0.75", "1.00")
BUDGETS = (("A", 0.50), ("B", 0.50), ("A", 1.00), ("B", 1.00), ("A", 1.50))


def by_k_table() -> str:
    lines = []
    for design, beta in BUDGETS:
        path = METRICS / f"r18_span_sweep_{design}_beta_{beta:.2f}.json"
        if not path.exists():
            continue
        d = json.loads(path.read_text(encoding="utf-8"))
        by_k = d["summary"]["by_k"]
        best = d["summary"]["best_k_counts"]
        n = d["summary"]["orbits"]
        lines.append(f"    \\multicolumn{{6}}{{@{{}}l}}{{\\emph{{Design~{design}, "
                     f"$\\beta = {beta:.2f}$, {n} orbits}}}}\\\\")
        for k in K_ALL:
            if k not in by_k:
                continue
            e = by_k[k]
            tag = {"0.00": "~(constant)", "1.00": "~(radial rule)"}.get(k, "")
            lines.append(
                f"    {k}{tag} & {e['median_span']:.2f} & "
                f"{e['median_error_m']:.3g} & "
                f"$\\times{e['median_total_work_ratio_vs_constant']:.3f}$ & "
                f"$\\times{e['median_rhs_ratio_vs_constant']:.3f}$ & "
                f"{int(best.get(k, 0))} \\\\")
        lines.append("    \\addlinespace[3pt]")
    body = "\n".join(lines[:-1])
    return ("% auto-generated by rev22_supplement_tables.py -- do not edit\n"
            "\\begin{tabular}{@{}l r r r r r@{}}\n\\toprule\n"
            "$k$ & span & error [m] & total work & RHS calls & best on \\\\\n"
            " & median & median & median & median & orbits \\\\\n"
            "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n")


def load_side(k: str, name: str, level: str = "tight") -> dict | None:
    p = CASES / f"k_{k}" / name / f"span_{level}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def longarc_table() -> tuple[str, dict]:
    d = json.loads((METRICS / "r20_span_longarc.json").read_text(encoding="utf-8"))
    rows = sorted(d["rows"], key=lambda r: r["hp_km"])
    lines, stats = [], {"percall": [], "rhs": [], "total": []}
    for r in rows:
        name = r["name"]
        base = load_side("0.00", name)
        mid = load_side("0.50", name)
        if base is None or mid is None:
            continue
        n0_sq = base["telemetry"]["mean_degree_sq"]
        percall = mid["telemetry"]["mean_degree_sq"] / n0_sq
        rhs = mid["telemetry"]["n_rhs"] / base["telemetry"]["n_rhs"]
        total = percall * rhs
        stats["percall"].append(percall)
        stats["rhs"].append(rhs)
        stats["total"].append(total)
        e = r["entries"]
        lines.append(
            f"    {r['hp_km']:.0f} & {e['0.00']['error_m']:.1f} & "
            f"{e['0.50']['error_m']:.1f} & {e['1.00']['error_m']:.0f} & "
            f"{e['0.00']['envelope_m'] + e['0.50']['envelope_m']:.0f} & "
            f"{percall:.3f} & {rhs:.3f} & {total:.3f} \\\\")
    table = ("% auto-generated by rev22_supplement_tables.py -- do not edit\n"
             "\\begin{tabular}{@{}r r r r r r r r@{}}\n\\toprule\n"
             "$h_p$ & \\multicolumn{3}{c}{sixty-day position RMS [m]} & env. & "
             "\\multicolumn{3}{c}{$k{=}0.5$ cost relative to $k{=}0$} \\\\\n"
             "\\cmidrule(lr){2-4}\\cmidrule(lr){6-8}\n"
             "[km] & $k{=}0$ & $k{=}0.5$ & $k{=}1$ & [m] & "
             "per call & RHS & total \\\\\n"
             "\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular}\n")
    summary = {kk: {"median": float(np.median(v)), "min": float(np.min(v)),
                    "max": float(np.max(v))} for kk, v in stats.items()}
    return table, summary


def main() -> int:
    (METRICS / "r18_by_k_table.tex").write_text(by_k_table(), encoding="utf-8")
    print("[r22] wrote r18_by_k_table.tex")
    table, summary = longarc_table()
    (METRICS / "r20_longarc_detail_table.tex").write_text(table, encoding="utf-8")
    (METRICS / "r22_longarc_cost_summary.json").write_text(
        json.dumps({"schema": "r22_longarc_cost_summary_v1",
                    "description": "realized cost of the k=0.5 member relative "
                                   "to the constant endpoint over sixty days, "
                                   "from the archived R20 telemetry",
                    "ratios": summary}, indent=1), encoding="utf-8")
    print("[r22] wrote r20_longarc_detail_table.tex")
    for k, v in summary.items():
        print(f"  {k:8s} median {v['median']:.3f}  range {v['min']:.3f}-{v['max']:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
