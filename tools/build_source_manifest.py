"""Regenerate docs/SOURCE_MANIFEST.md from the modules under src/.

    python tools/build_source_manifest.py
    python tools/build_source_manifest.py --check

``--check`` rewrites nothing and exits non-zero if the committed manifest no
longer describes the tree, which is what CI uses.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "docs" / "SOURCE_MANIFEST.md"

HEADER = (
    "# Source manifest\n\n"
    "SHA-256 of every module under `src/`, as committed. `verify_snapshot.py`\n"
    "exercises this code against recorded reference values; these digests let a\n"
    "reader confirm the files have not changed since. Regenerated by\n"
    "[`tools/build_source_manifest.py`](../tools/build_source_manifest.py).\n\n"
    "| file | sha256 |\n|---|---|\n"
)


def render() -> str:
    rows = [(p.relative_to(ROOT).as_posix(),
             hashlib.sha256(p.read_bytes()).hexdigest())
            for p in sorted(SRC.rglob("*.py"))]
    return HEADER + "".join(f"| `{rel}` | `{digest}` |\n" for rel, digest in rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify without rewriting")
    args = parser.parse_args()

    rendered = render()
    count = rendered.count("\n| `src/")

    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == rendered:
            print(f"[ok] {OUT.relative_to(ROOT)} matches {count} modules")
            return 0
        print(f"[stale] {OUT.relative_to(ROOT)} does not match src/; "
              f"run tools/build_source_manifest.py")
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {count} modules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
