"""Reject accidental edits to the archive's frozen evidence.

The scientific archive is append-only: a new campaign may add newly named
artifacts, but maintenance work must not rewrite, move, or delete historical
ones. The commit-pinned measurement snapshot under ``src/`` is fully frozen,
including additions.

This check compares two Git revisions, so changing both an artifact and its
manifest in the same commit cannot hide the edit.

    python tools/check_frozen_changes.py --base <base-sha>
    python tools/check_frozen_changes.py --base HEAD --working-tree

With no ``--base``, ``ARCHIVE_GUARD_BASE`` is used. If that is also absent,
the first parent of ``HEAD`` is used.
"""

from __future__ import annotations

import argparse
import os
import subprocess
from dataclasses import dataclass
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parents[1]

APPEND_ONLY_ROOTS = {
    "archive",
    "data",
    "environments",
    "experiments",
    "figures",
    "metrics",
    "scripts",
}

FULLY_FROZEN_ROOTS = {"src"}

# Documentation that lives inside an append-only root but is regenerated by a
# maintenance tool, not sealed by any manifest.
MAINTAINED_DOCS = {
    "environments/README.md",
}

FULLY_FROZEN_FILES = {
    ".gitattributes",
    "audit_manifest_digests.py",
    "docs/SOURCE_MANIFEST.md",
    "fetch_data.py",
    "known_stale_digests.json",
    "requirements-smoke-test.txt",
    "verify_snapshot.py",
}


@dataclass(frozen=True)
class Change:
    status: str
    paths: tuple[str, ...]


def normalize(path: str) -> str:
    return PurePosixPath(path.replace("\\", "/")).as_posix()


def root_of(path: str) -> str:
    return normalize(path).split("/", 1)[0]


def is_fully_frozen(path: str) -> bool:
    path = normalize(path)
    return path in FULLY_FROZEN_FILES or root_of(path) in FULLY_FROZEN_ROOTS


def is_append_only(path: str) -> bool:
    path = normalize(path)
    return root_of(path) in APPEND_ONLY_ROOTS and path not in MAINTAINED_DOCS


def parse_name_status(text: str) -> list[Change]:
    changes: list[Change] = []
    for raw in text.splitlines():
        if not raw.strip():
            continue
        fields = raw.split("\t")
        status = fields[0]
        expected_paths = 2 if status.startswith(("R", "C")) else 1
        if len(fields) != expected_paths + 1:
            raise ValueError(f"cannot parse git diff line: {raw!r}")
        changes.append(Change(status=status,
                              paths=tuple(normalize(p) for p in fields[1:])))
    return changes


def violation_reason(change: Change) -> str | None:
    status_kind = change.status[0]

    # The source snapshot and root verification contract are immutable even
    # when the proposed path is new.
    frozen = [path for path in change.paths if is_fully_frozen(path)]
    if frozen:
        return f"fully frozen path touched: {', '.join(frozen)}"

    protected = [path for path in change.paths if is_append_only(path)]
    if not protected:
        return None

    # A genuinely new filename extends the evidence without changing history.
    if status_kind == "A" and len(change.paths) == 1:
        return None

    return ("existing append-only evidence changed; add a newly named artifact "
            f"instead: {', '.join(protected)}")


def classify(changes: list[Change]) -> tuple[list[Change], list[tuple[Change, str]]]:
    allowed: list[Change] = []
    blocked: list[tuple[Change, str]] = []
    for change in changes:
        reason = violation_reason(change)
        if reason is None:
            allowed.append(change)
        else:
            blocked.append((change, reason))
    return allowed, blocked


def git(*args: str) -> str:
    result = subprocess.run(
        ["git", "-c", f"safe.directory={ROOT.as_posix()}", *args],
        cwd=ROOT, check=True, capture_output=True, text=True,
        encoding="utf-8",
    )
    return result.stdout.strip()


def default_base() -> str:
    configured = os.environ.get("ARCHIVE_GUARD_BASE", "").strip()
    if configured and set(configured) != {"0"}:
        return configured
    return git("rev-parse", "HEAD^")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", help="base commit or ref")
    parser.add_argument("--head", default="HEAD", help="head commit or ref")
    parser.add_argument(
        "--working-tree", action="store_true",
        help="compare the base with staged, unstaged, and untracked files",
    )
    args = parser.parse_args()

    base = args.base or default_base()
    if args.working_tree:
        diff = git("diff", "--name-status", "--find-renames", base)
    else:
        diff = git("diff", "--name-status", "--find-renames",
                   f"{base}..{args.head}")
    changes = parse_name_status(diff)
    if args.working_tree:
        represented = {path for change in changes for path in change.paths}
        untracked = git("ls-files", "--others", "--exclude-standard")
        changes.extend(
            Change("A", (normalize(path),))
            for path in untracked.splitlines()
            if path and normalize(path) not in represented
        )
    allowed, blocked = classify(changes)

    print(f"archive guard base : {base}")
    print(f"changes inspected  : {len(changes)}")
    print(f"allowed            : {len(allowed)}")
    print(f"blocked            : {len(blocked)}")

    for change, reason in blocked:
        print(f"  [blocked] {change.status:4s} {' -> '.join(change.paths)}")
        print(f"            {reason}")

    if blocked:
        print("\nHistorical evidence is immutable. Restore the existing file and "
              "add a newly named artifact for a new campaign.")
        return 1

    print("[ok] no frozen evidence was modified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
